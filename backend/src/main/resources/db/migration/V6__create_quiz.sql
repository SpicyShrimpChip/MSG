-- 퀴즈(객관식)와 제출 기록. 채점은 서버 코드가 하고, AI는 문제와 해설(ai_explanation)만 쓴다.
-- 퀴즈는 올린 본인만 본다. 회원·과목·자료를 지우면 그 퀴즈와 제출 기록도 함께 지워진다.
-- H2(PostgreSQL 모드)와 PostgreSQL에서 모두 돌도록 DB 전용 문법을 쓰지 않는다

CREATE TABLE quiz (
    id          BIGINT       GENERATED BY DEFAULT AS IDENTITY,
    user_id     BIGINT       NOT NULL,
    course_id   BIGINT       NOT NULL,
    -- 이 퀴즈를 만든 자료. 약점 개념으로 만든 퀴즈처럼 자료가 없으면 NULL
    material_id BIGINT       NULL,
    title       VARCHAR(100) NOT NULL,
    created_at  TIMESTAMP(6) NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT fk_quiz_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT fk_quiz_course FOREIGN KEY (course_id) REFERENCES course (id) ON DELETE CASCADE,
    CONSTRAINT fk_quiz_material FOREIGN KEY (material_id) REFERENCES material (id) ON DELETE CASCADE
);

CREATE INDEX idx_quiz_user ON quiz (user_id);
CREATE INDEX idx_quiz_course ON quiz (course_id);
CREATE INDEX idx_quiz_material ON quiz (material_id);

-- 문제. 정답 번호는 제출 뒤 결과에만 내보낸다 (풀기 화면 응답에는 넣지 않는다)
CREATE TABLE quiz_question (
    id                   BIGINT        GENERATED BY DEFAULT AS IDENTITY,
    quiz_id              BIGINT        NOT NULL,
    sort_order           INTEGER       NOT NULL,
    content              VARCHAR(1000) NOT NULL,
    -- 보기 순서(quiz_choice.sort_order, 0부터)
    correct_choice_index INTEGER       NOT NULL,
    -- AI가 쓴 해설. 없으면 NULL
    ai_explanation       VARCHAR(2000) NULL,
    PRIMARY KEY (id),
    CONSTRAINT uk_quiz_question_order UNIQUE (quiz_id, sort_order),
    CONSTRAINT fk_quiz_question_quiz FOREIGN KEY (quiz_id) REFERENCES quiz (id) ON DELETE CASCADE
);

CREATE TABLE quiz_choice (
    question_id BIGINT       NOT NULL,
    sort_order  INTEGER      NOT NULL,
    content     VARCHAR(500) NOT NULL,
    PRIMARY KEY (question_id, sort_order),
    CONSTRAINT fk_quiz_choice_question FOREIGN KEY (question_id) REFERENCES quiz_question (id) ON DELETE CASCADE
);

-- 문제가 다루는 개념. concept_key는 학습 분석의 concept_key와 같은 규칙(과목 키워드를 소문자로 맞춘 값)이다
CREATE TABLE quiz_question_concept (
    question_id  BIGINT      NOT NULL,
    sort_order   INTEGER     NOT NULL,
    concept_key  VARCHAR(20) NOT NULL,
    concept_name VARCHAR(20) NOT NULL,
    PRIMARY KEY (question_id, sort_order),
    CONSTRAINT fk_quiz_question_concept_question FOREIGN KEY (question_id)
        REFERENCES quiz_question (id) ON DELETE CASCADE
);

-- 제출 한 번. 같은 퀴즈를 여러 번 풀 수 있고, 목록·결과 화면은 가장 최근 제출(id가 가장 큰 것)을 쓴다
CREATE TABLE quiz_submission (
    id            BIGINT       GENERATED BY DEFAULT AS IDENTITY,
    quiz_id       BIGINT       NOT NULL,
    user_id       BIGINT       NOT NULL,
    correct_count INTEGER      NOT NULL,
    total_count   INTEGER      NOT NULL,
    submitted_at  TIMESTAMP(6) NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT fk_quiz_submission_quiz FOREIGN KEY (quiz_id) REFERENCES quiz (id) ON DELETE CASCADE,
    CONSTRAINT fk_quiz_submission_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE
);

CREATE INDEX idx_quiz_submission_quiz ON quiz_submission (quiz_id, id);
CREATE INDEX idx_quiz_submission_user ON quiz_submission (user_id);

-- 문제별 채점 결과. 답하지 않은 문제는 choice_index -1(틀림)로 남긴다
CREATE TABLE quiz_answer (
    id            BIGINT  GENERATED BY DEFAULT AS IDENTITY,
    submission_id BIGINT  NOT NULL,
    question_id   BIGINT  NOT NULL,
    choice_index  INTEGER NOT NULL,
    correct       BOOLEAN NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT uk_quiz_answer UNIQUE (submission_id, question_id),
    CONSTRAINT fk_quiz_answer_submission FOREIGN KEY (submission_id)
        REFERENCES quiz_submission (id) ON DELETE CASCADE,
    CONSTRAINT fk_quiz_answer_question FOREIGN KEY (question_id)
        REFERENCES quiz_question (id) ON DELETE CASCADE
);

CREATE INDEX idx_quiz_answer_question ON quiz_answer (question_id);
