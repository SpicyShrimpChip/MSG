-- 개념별 숙련도 기록 (변화 추이용). 대시보드가 숙련도를 계산할 때 그 개념의 마지막 기록과 단계·근거가 달라졌으면 한 행을 남긴다.
-- 값은 MasteryCalculator가 규칙(app.mastery)으로 계산한 것이고 LLM이 정하지 않는다. 산식을 바꾸면 formula_version으로 구분한다.
-- 개념은 과목 키워드(concept_key)로 가리킨다. 대화 분석 결과에서 나온 값이라 analysis_run을 지우면(대화 삭제·동의 철회) 함께 지워진다.
-- H2(PostgreSQL 모드)와 PostgreSQL에서 모두 돈다

CREATE TABLE concept_mastery (
    id                   BIGINT           GENERATED BY DEFAULT AS IDENTITY,
    user_id              BIGINT           NOT NULL,
    course_id            BIGINT           NOT NULL,
    -- 이 값을 계산할 때 쓴 분석
    analysis_run_id      BIGINT           NOT NULL,
    concept_key          VARCHAR(20)      NOT NULL,
    concept_name         VARCHAR(20)      NOT NULL,
    -- insufficient_evidence / needs_work / normal / strong
    level                VARCHAR(30)      NOT NULL,
    -- 0~1, 근거 부족이면 NULL. 화면에 숫자로 보여 주지 않는다
    score                DOUBLE PRECISION NULL,
    evidence_weight      DOUBLE PRECISION NOT NULL,
    quiz_graded_count    INTEGER          NOT NULL,
    quiz_rate            DOUBLE PRECISION NULL,
    conversation_count   INTEGER          NOT NULL,
    conversation_status  VARCHAR(20)      NULL,
    formula_version      VARCHAR(20)      NOT NULL,
    recorded_at          TIMESTAMP(6)     NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT fk_concept_mastery_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT fk_concept_mastery_course FOREIGN KEY (course_id) REFERENCES course (id) ON DELETE CASCADE,
    CONSTRAINT fk_concept_mastery_run FOREIGN KEY (analysis_run_id) REFERENCES analysis_run (id) ON DELETE CASCADE
);

CREATE INDEX idx_concept_mastery_course ON concept_mastery (user_id, course_id, concept_key, id);
