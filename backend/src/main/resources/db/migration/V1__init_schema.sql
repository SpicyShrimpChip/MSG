-- ==================== 자료 핵심 개념·개념 학습·숙련도 ====================

-- 학습자료에서 뽑은 핵심 개념과 근거(자료 안의 위치·문장). 사전·사후평가가 이 개념 체계로 문제를 만든다.
-- 자료나 회원을 지우면 함께 지워진다. 자료 본문 전체는 저장하지 않고, 근거 문장(300자까지)만 남긴다
CREATE TABLE material_concept (
    id                BIGINT        GENERATED BY DEFAULT AS IDENTITY,
    material_id       BIGINT        NOT NULL,
    user_id           BIGINT        NOT NULL,
    sort_order        INTEGER       NOT NULL,
    -- 개념 이름을 소문자로 맞춘 값 (퀴즈 개념 키·과목 키워드와 같은 규칙)
    concept_key       VARCHAR(20)   NOT NULL,
    name              VARCHAR(20)   NOT NULL,
    -- AI가 쓴 짧은 설명
    description       VARCHAR(300)  NULL,
    -- 근거 위치 (서버가 본문에서 찾은 쪽·슬라이드, 예: "p. 3", "슬라이드 2"). 위치 표시가 없는 글이면 NULL
    evidence_location VARCHAR(40)   NULL,
    -- 근거 문장. 서버가 실제 본문에 있는지 확인한 것만 저장한다
    evidence_quote    VARCHAR(300)  NOT NULL,
    -- 과목 키워드와 같은 개념인지 (자료에서 새로 찾은 개념과 구분)
    course_keyword    BOOLEAN       NOT NULL,
    provider          VARCHAR(10)   NOT NULL,
    model             VARCHAR(100)  NULL,
    created_at        TIMESTAMP(6)  NOT NULL,
    -- 학습용 설명 (AI가 자료 본문 발췌를 근거로 쓴 글). 개념을 뽑은 뒤 "자세한 설명 만들기"로 채운다.
    -- 개념을 다시 뽑으면 행이 바뀌므로 설명도 함께 사라진다.
    -- context_quote는 서버가 자료 본문에 실제로 있는지 확인한 문장만 저장한다(확인 못 하면 NULL)
    explanation       VARCHAR(1200) NULL,
    material_context  VARCHAR(500)  NULL,
    context_quote     VARCHAR(300)  NULL,
    context_location  VARCHAR(40)   NULL,
    importance        VARCHAR(500)  NULL,
    example           VARCHAR(500)  NULL,
    note_provider     VARCHAR(10)   NULL,
    note_model        VARCHAR(100)  NULL,
    note_created_at   TIMESTAMP(6)  NULL,
    PRIMARY KEY (id),
    CONSTRAINT uk_material_concept UNIQUE (material_id, concept_key),
    CONSTRAINT fk_material_concept_material FOREIGN KEY (material_id) REFERENCES material (id) ON DELETE CASCADE,
    CONSTRAINT fk_material_concept_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE
);

CREATE INDEX idx_material_concept_material ON material_concept (material_id, sort_order);

-- 개념별 학습 기록 (사용자가 자료의 핵심 개념을 공부하고 "학습 완료"를 누른 기록).
-- 개념은 (자료, 개념 키)로 가리킨다: material_concept 행은 "다시 뽑기" 때 새로 만들어져 id가 바뀌지만, 개념 키는 그대로라 기록이 이어진다.
-- 같은 이름의 개념도 자료가 다르면 다른 기록이다. 사용자·자료마다 개념 하나에 한 행(중복 완료 방지).
-- "학습 완료"는 공부했다는 기록일 뿐 이해했다는 뜻이 아니다. 이해 여부는 확인 퀴즈(quiz.check_concept_key) 채점 결과로만 정한다.
-- 퀴즈 결과는 이 표에 복사하지 않고 퀴즈 기록에서 읽는다(다시 채점하면 바로 반영, 지난 결과는 퀴즈 행으로 남는다)
CREATE TABLE concept_study_progress (
    id                  BIGINT       GENERATED BY DEFAULT AS IDENTITY,
    user_id             BIGINT       NOT NULL,
    course_id           BIGINT       NOT NULL,
    material_id         BIGINT       NOT NULL,
    -- material_concept.concept_key와 같은 값 (개념 이름을 소문자로 맞춘 값)
    concept_key         VARCHAR(20)  NOT NULL,
    -- 표시용 개념 이름 (기록할 때의 이름)
    concept_name        VARCHAR(20)  NOT NULL,
    first_completed_at  TIMESTAMP(6) NOT NULL,
    last_studied_at     TIMESTAMP(6) NOT NULL,
    -- 학습 완료 횟수: 처음 1, "복습 필요"였다가 다시 공부하고 완료하면 1씩 늘어난다 (같은 상태에서 다시 눌러도 늘지 않는다)
    study_count         INTEGER      NOT NULL,
    created_at          TIMESTAMP(6) NOT NULL,
    updated_at          TIMESTAMP(6) NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT uk_concept_study_progress UNIQUE (user_id, material_id, concept_key),
    CONSTRAINT fk_concept_study_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT fk_concept_study_course FOREIGN KEY (course_id) REFERENCES course (id) ON DELETE CASCADE,
    CONSTRAINT fk_concept_study_material FOREIGN KEY (material_id) REFERENCES material (id) ON DELETE CASCADE
);

CREATE INDEX idx_concept_study_course ON concept_study_progress (user_id, course_id);
CREATE INDEX idx_quiz_check_concept ON quiz (user_id, material_id, check_concept_key);

-- 개념별 숙련도 기록 (변화 추이용). 대시보드가 숙련도를 계산할 때 그 개념의 마지막 기록과 단계·근거가 달라졌으면 한 행을 남긴다.
-- 값은 MasteryCalculator가 규칙(app.mastery)으로 계산한 것이고 LLM이 정하지 않는다. 산식을 바꾸면 formula_version으로 구분한다.
-- 개념은 과목 키워드(concept_key)로 가리킨다. 대화 분석 결과에서 나온 값이라 analysis_run을 지우면(대화 삭제·동의 철회) 함께 지워진다
CREATE TABLE concept_mastery (
    id                   BIGINT           GENERATED BY DEFAULT AS IDENTITY,
