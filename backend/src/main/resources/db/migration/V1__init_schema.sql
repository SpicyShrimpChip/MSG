-- MSG 처음 스키마 (PostgreSQL 16 + H2 PostgreSQL 모드).
-- 11/24 운영 DB를 처음 만들기 전에 V1~V16을 이 파일 하나로 합쳐 다시 시작했다(10/31 #82에 이어 두 번째, 운영 DB가 생긴 뒤에는 하지 않는다).
-- 합치기 전 스키마와 pg_dump(--schema-only)로 비교해 같은 것을 확인했다. 그래서 나중에 더한 열은 표 끝에 둔다(열 순서까지 같게).
-- 이 파일부터는 머지된 뒤 고치지 않고 V2부터 새 버전을 추가한다.
-- H2(PostgreSQL 모드)와 PostgreSQL에서 모두 돌도록 DB 전용 문법(SERIAL, 배열, JSONB 등)을 쓰지 않는다.
-- pgvector 확장은 db/vector(local·prod·pgTest만), 로컬 확인용 공지는 db/seed(prod 제외)에 있다

-- ==================== 회원·세션·공지 ====================

-- 회원. 모든 사용자별 학습 데이터는 users.id를 외래 키로 가진다 (docs/backend-design.md)
CREATE TABLE users (
    id                       BIGINT       GENERATED BY DEFAULT AS IDENTITY,
    -- 소문자로 바꿔 저장한다. 중복 가입은 애플리케이션 검사와 이 UNIQUE 제약으로 함께 막는다
    email                    VARCHAR(254) NOT NULL,
    -- BCrypt 해시 (원본 비밀번호는 저장하지 않는다)
    password_hash            VARCHAR(100) NOT NULL,
    name                     VARCHAR(30)  NOT NULL,
    role                     VARCHAR(20)  NOT NULL,
    -- AI 대화 분석 동의(선택). 철회하면 가져온 대화와 분석 결과를 함께 삭제한다
    ai_analysis_consent      BOOLEAN      NOT NULL,
    ai_analysis_consented_at TIMESTAMP(6) NULL,
    terms_agreed_at          TIMESTAMP(6) NOT NULL,
    privacy_agreed_at        TIMESTAMP(6) NOT NULL,
    created_at               TIMESTAMP(6) NOT NULL,
    updated_at               TIMESTAMP(6) NOT NULL,
    -- 주된 학습 목적. 처음에는 '아직 정하지 않음'. 퀴즈를 만들 때는 이와 다른 모드를 골라도 된다
    learning_purpose         VARCHAR(20)  DEFAULT 'UNDECIDED' NOT NULL,
    -- 관심 직무 (업무 활용 모드에서 쓴다). 고르지 않았으면 NULL. 목록은 코드(JobField)에 있고 늘릴 수 있다
    job_field                VARCHAR(40)  NULL,
    -- 관심 직무가 '기타'일 때 직접 쓴 분야 이름 (짧게)
    job_field_other          VARCHAR(30)  NULL,
    -- AI 퀴즈 처리 동의(선택). 퀴즈 만들기·주관식·서술형 AI 채점 때 과목 이름·개념·시험 범위·직무·학습자 답을 외부 AI로 보내는 데 대한 동의.
    -- AI 대화 분석 동의(ai_analysis_consent)와 목적·항목이 달라 따로 받는다. 기본은 동의하지 않음(자동 동의 금지)
    ai_quiz_consent          BOOLEAN      DEFAULT FALSE NOT NULL,
    ai_quiz_consented_at     TIMESTAMP(6) NULL,
    PRIMARY KEY (id),
    CONSTRAINT uk_users_email UNIQUE (email)
);

-- 로그인 세션별 Refresh Token. 원문은 저장하지 않고 SHA-256 해시만 저장한다.
-- 갱신할 때마다 새 행을 만들고 이전 행은 revoked_at을 채운다 (토큰 회전).
-- 이미 폐기된 토큰이 다시 오면 같은 session_id의 행을 모두 폐기한다 (재사용 감지)
CREATE TABLE refresh_token (
    id         BIGINT       GENERATED BY DEFAULT AS IDENTITY,
    user_id    BIGINT       NOT NULL,
    session_id VARCHAR(36)  NOT NULL,
    token_hash VARCHAR(64)  NOT NULL,
    expires_at TIMESTAMP(6) NOT NULL,
    created_at TIMESTAMP(6) NOT NULL,
    revoked_at TIMESTAMP(6) NULL,
    PRIMARY KEY (id),
    CONSTRAINT uk_refresh_token_hash UNIQUE (token_hash),
    -- 탈퇴하면 세션도 함께 지운다
    CONSTRAINT fk_refresh_token_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE
);

CREATE INDEX idx_refresh_token_session ON refresh_token (session_id);
CREATE INDEX idx_refresh_token_user ON refresh_token (user_id);

-- 공지사항. 본문은 글자만 저장한다 (HTML·마크다운으로 해석하지 않는다).
-- 본문·수정 시각은 비워 둘 수 있게 하고, 작성·수정할 때는 API가 제목과 본문을 모두 요구한다.
-- TEXT 대신 VARCHAR로 둔 것은 Hibernate 검증(ddl-auto: validate)이 H2와 PostgreSQL에서 같게 통과하게 하기 위해서다
CREATE TABLE notice (
    id         BIGINT       GENERATED BY DEFAULT AS IDENTITY,
    title      VARCHAR(100) NOT NULL,
    content    VARCHAR(5000),
    created_at DATE         NOT NULL,
    updated_at TIMESTAMP(6),
    -- 작성한 관리자가 탈퇴해도 공지는 남는다
    author_id  BIGINT,
    PRIMARY KEY (id),
    CONSTRAINT fk_notice_author FOREIGN KEY (author_id) REFERENCES users (id) ON DELETE SET NULL
);

CREATE INDEX idx_notice_created_at ON notice (created_at);

-- ==================== 내 과목 ====================

-- 내 과목 (학습자료 > 내 과목). 과목은 로그인한 사용자별로 나뉜다
CREATE TABLE course (
    id         BIGINT       GENERATED BY DEFAULT AS IDENTITY,
    user_id    BIGINT       NOT NULL,
    name       VARCHAR(40)  NOT NULL,
    -- 중복 검사용: 이름을 소문자로 바꾼 값. 같은 사용자·같은 학기에 대소문자만 다른 이름도 막는다
    -- (H2와 PostgreSQL이 함께 쓰는 문법으로는 LOWER(name) 인덱스를 만들 수 없어 컬럼으로 둔다)
    name_key   VARCHAR(80)  NOT NULL,
    -- '2026-1', '2026-summer', '2026-2', '2026-winter'
    semester   VARCHAR(20)  NOT NULL,
    created_at TIMESTAMP(6) NOT NULL,
    updated_at TIMESTAMP(6) NOT NULL,
    PRIMARY KEY (id),
    -- user_id로 시작하므로 사용자별 과목 조회 인덱스도 겸한다
    CONSTRAINT uk_course_user_semester_name UNIQUE (user_id, semester, name_key),
    CONSTRAINT fk_course_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE
);

-- 과목 키워드. AI 대화 가져오기에서 공부한 대화를 고를 때 쓴다. 입력한 순서를 sort_order로 지킨다
CREATE TABLE course_keyword (
    course_id  BIGINT      NOT NULL,
    sort_order INTEGER     NOT NULL,
    keyword    VARCHAR(20) NOT NULL,
    PRIMARY KEY (course_id, sort_order),
    CONSTRAINT fk_course_keyword_course FOREIGN KEY (course_id) REFERENCES course (id) ON DELETE CASCADE
);

-- ==================== 학습자료 ====================

-- 학습자료(올린 파일의 정보). 파일 내용은 저장소(global/storage, 지금은 로컬 디스크)에 두고 DB에는 정보와 저장 위치(storage_key)만 둔다
CREATE TABLE material (
    id                 BIGINT       GENERATED BY DEFAULT AS IDENTITY,
    user_id            BIGINT       NOT NULL,
    -- 과목에 연결하지 않은 자료는 NULL
    course_id          BIGINT       NULL,
    title              VARCHAR(60)  NOT NULL,
    -- 화면에 보여 줄 원래 파일 이름 (경로 부분을 떼고 정리한 값). 저장 위치에는 쓰지 않는다
    original_file_name VARCHAR(255) NOT NULL,
    -- 서버가 내용을 확인한 형식: PDF, PPTX, TXT, MD
    file_format        VARCHAR(10)  NOT NULL,
    -- 형식에서 정한 MIME (브라우저가 보낸 값을 믿지 않는다)
    content_type       VARCHAR(100) NOT NULL,
    file_size          BIGINT       NOT NULL,
    -- 저장소 안의 위치. 서버가 만든 값(materials/{user_id}/{UUID}.{확장자})이다.
    -- 원본 보관 정책이 정해져 원본만 지우는 경우를 위해 NULL을 허용한다
    storage_key        VARCHAR(200) NULL,
    -- UPLOADED(저장 완료, AI 분석 전) / PROCESSING / READY / FAILED
    status             VARCHAR(20)  NOT NULL,
    created_at         TIMESTAMP(6) NOT NULL,
    updated_at         TIMESTAMP(6) NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT uk_material_storage_key UNIQUE (storage_key),
    -- 회원 탈퇴 때 행은 함께 지워진다. 저장소 파일은 탈퇴 처리 코드가 따로 지워야 한다 (docs/backend-design.md)
    CONSTRAINT fk_material_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
    -- 과목을 지우면 그 과목의 자료도 지운다. 앱은 파일 정리 작업을 남기려고 자료를 먼저 지우고, 이 제약은 마지막 안전장치다
    CONSTRAINT fk_material_course FOREIGN KEY (course_id) REFERENCES course (id) ON DELETE CASCADE
);

CREATE INDEX idx_material_user_created ON material (user_id, created_at);
CREATE INDEX idx_material_course ON material (course_id);

-- 지워야 할 저장소 파일. 자료 행을 지우는 트랜잭션에서 함께 만들고, 커밋 뒤 파일을 지우면 행도 지운다.
-- 파일을 지우지 못하면 행이 남아 주기 작업이 다시 지운다 (FileCleanupService)
CREATE TABLE file_deletion_task (
    id                BIGINT       GENERATED BY DEFAULT AS IDENTITY,
    storage_key       VARCHAR(200) NOT NULL,
    attempt_count     INTEGER      NOT NULL,
    created_at        TIMESTAMP(6) NOT NULL,
    last_attempted_at TIMESTAMP(6) NULL,
    PRIMARY KEY (id)
);

-- ==================== AI 대화 가져오기 ====================
-- 외부 AI(ChatGPT·Claude)에서 가져온 대화. 프론트가 브라우저에서 개인정보를 가린 뒤 보낸 글만 저장한다
-- (원본 내보내기 파일은 서버로 오지 않는다). 서버도 개인정보 패턴을 한 번 더 검사하고, 남아 있으면 저장하지 않는다

-- 가져오기 작업 하나 = 사용자가 "보내기"를 한 번 누른 것. 프론트는 대화를 과목별·크기별로 나눠 여러 요청으로 보내고,
-- 모든 요청(request_count개)을 받아야 COMPLETED가 된다. AI 분석은 COMPLETED 작업의 대화만 쓴다
CREATE TABLE conversation_import (
    id               BIGINT       GENERATED BY DEFAULT AS IDENTITY,
    user_id          BIGINT       NOT NULL,
    -- 프론트가 만든 작업 id(UUID). 같은 id로 다시 보내면 같은 작업으로 이어 받는다
    client_import_id VARCHAR(36)  NOT NULL,
    request_count    INTEGER      NOT NULL,
    -- IN_PROGRESS / COMPLETED
    status           VARCHAR(20)  NOT NULL,
    created_at       TIMESTAMP(6) NOT NULL,
    completed_at     TIMESTAMP(6) NULL,
    PRIMARY KEY (id),
    CONSTRAINT uk_conversation_import_client UNIQUE (user_id, client_import_id),
    CONSTRAINT fk_conversation_import_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE
);

-- 작업에서 이미 받은 요청 번호. 같은 요청을 다시 받으면 저장하지 않고 같은 결과를 돌려준다
CREATE TABLE conversation_import_request (
    id                 BIGINT       GENERATED BY DEFAULT AS IDENTITY,
    import_id          BIGINT       NOT NULL,
    request_index      INTEGER      NOT NULL,
    conversation_count INTEGER      NOT NULL,
    created_at         TIMESTAMP(6) NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT uk_conversation_import_request UNIQUE (import_id, request_index),
    CONSTRAINT fk_conversation_import_request_import FOREIGN KEY (import_id)
        REFERENCES conversation_import (id) ON DELETE CASCADE
);

-- 대화 하나. 긴 대화는 조각(part)으로 나뉘어 여러 요청으로 올 수 있고, 조각을 모두 받아야 완성된다
CREATE TABLE conversation (
    id                  BIGINT       GENERATED BY DEFAULT AS IDENTITY,
    user_id             BIGINT       NOT NULL,
    course_id           BIGINT       NOT NULL,
    -- 이 대화를 마지막으로 보낸 가져오기 작업. 그 작업이 COMPLETED이고 조각을 모두 받았을 때만 분석에 쓴다
    import_id           BIGINT       NOT NULL,
    -- CHATGPT / CLAUDE
    source              VARCHAR(20)  NOT NULL,
    -- 내보내기 파일 안의 대화 id (나눠 보낸 대화는 원래 id). 같은 사용자·서비스에서 한 번만 저장한다
    client_id           VARCHAR(200) NOT NULL,
    title               VARCHAR(500) NOT NULL,
    -- 외부 서비스에서 대화를 시작한 시각 (파일에 없으면 NULL)
    source_created_at   TIMESTAMP(6) NULL,
    part_count          INTEGER      NOT NULL,
    received_part_count INTEGER      NOT NULL,
    message_count       INTEGER      NOT NULL,
    created_at          TIMESTAMP(6) NOT NULL,
    updated_at          TIMESTAMP(6) NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT uk_conversation_client UNIQUE (user_id, source, client_id),
    CONSTRAINT fk_conversation_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
    -- 과목을 지우면 그 과목에 가져온 대화도 지운다 (학습자료와 같은 규칙)
    CONSTRAINT fk_conversation_course FOREIGN KEY (course_id) REFERENCES course (id) ON DELETE CASCADE,
    -- 작업 행은 따로 지우지 않는다. 회원 탈퇴 때 users에서 함께 지워지는 순서와 상관없게 CASCADE로 둔다
    CONSTRAINT fk_conversation_import FOREIGN KEY (import_id) REFERENCES conversation_import (id) ON DELETE CASCADE
);

CREATE INDEX idx_conversation_user_created ON conversation (user_id, created_at);
CREATE INDEX idx_conversation_course ON conversation (course_id);
CREATE INDEX idx_conversation_import ON conversation (import_id);

-- 받은 조각. 조각 없이 온 대화는 1번 조각 하나로 기록한다
CREATE TABLE conversation_part (
    id              BIGINT       GENERATED BY DEFAULT AS IDENTITY,
    conversation_id BIGINT       NOT NULL,
    part_index      INTEGER      NOT NULL,
    message_count   INTEGER      NOT NULL,
    created_at      TIMESTAMP(6) NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT uk_conversation_part UNIQUE (conversation_id, part_index),
    CONSTRAINT fk_conversation_part_conversation FOREIGN KEY (conversation_id)
        REFERENCES conversation (id) ON DELETE CASCADE
);

-- 메시지. 대화 안의 순서는 (part_index, seq)다.
-- 20,000자가 넘는 메시지는 프론트가 나눠 보내고, 이어지는 글이 다음 메시지에 있으면 continued가 TRUE다
CREATE TABLE conversation_message (
    id              BIGINT         GENERATED BY DEFAULT AS IDENTITY,
    conversation_id BIGINT         NOT NULL,
    part_index      INTEGER        NOT NULL,
    seq             INTEGER        NOT NULL,
    -- USER / ASSISTANT
    role            VARCHAR(10)    NOT NULL,
    content         VARCHAR(20000) NOT NULL,
    continued       BOOLEAN        NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT uk_conversation_message UNIQUE (conversation_id, part_index, seq),
    CONSTRAINT fk_conversation_message_conversation FOREIGN KEY (conversation_id)
        REFERENCES conversation (id) ON DELETE CASCADE
);

-- ==================== 학습 대화 분석 (세 모델 독립 판단) ====================
-- 여러 AI 모델(GPT·Claude·Gemini)이 같은 대화를 독립적으로 분석한 결과와 모델 사이 비교,
-- 그리고 학습 모드에서 사용자가 남긴 피드백. AI 결과는 받은 그대로 보관하고, 사용자 피드백은 따로 둔다.
-- 숙련도는 여기서 만들지 않는다 (규칙 코드가 계산해 concept_mastery에 남긴다)

-- 분석 한 번 = 과목 하나의 분석 대상 대화를 모든 모델에 한 번씩 보낸 것
CREATE TABLE analysis_run (
    id                      BIGINT       GENERATED BY DEFAULT AS IDENTITY,
    user_id                 BIGINT       NOT NULL,
    course_id               BIGINT       NOT NULL,
    -- RUNNING / COMPLETED(모든 호출 모델 성공) / PARTIAL(일부 성공) / FAILED(성공한 모델 없음)
    status                  VARCHAR(20)  NOT NULL,
    -- 모델에 준 지시문 버전. 지시문을 바꾸면 결과를 같은 기준으로 비교하지 않는다
    prompt_version          VARCHAR(40)  NOT NULL,
    conversation_count      INTEGER      NOT NULL,
    message_count           INTEGER      NOT NULL,
    -- 길어서 뒤를 잘라 보낸 메시지 수
    truncated_message_count INTEGER      NOT NULL,
    input_chars             INTEGER      NOT NULL,
    created_at              TIMESTAMP(6) NOT NULL,
    completed_at            TIMESTAMP(6) NULL,
    PRIMARY KEY (id),
    CONSTRAINT fk_analysis_run_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT fk_analysis_run_course FOREIGN KEY (course_id) REFERENCES course (id) ON DELETE CASCADE
);

CREATE INDEX idx_analysis_run_user_created ON analysis_run (user_id, created_at);
CREATE INDEX idx_analysis_run_course ON analysis_run (course_id);

-- 분석에 쓴 대화. 대화를 지우면 그 대화를 쓴 분석을 앱이 함께 지운다(AnalysisCleanup). 이 외래 키는 마지막 안전장치다
CREATE TABLE analysis_run_conversation (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY,
    run_id          BIGINT NOT NULL,
    conversation_id BIGINT NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT uk_analysis_run_conversation UNIQUE (run_id, conversation_id),
    CONSTRAINT fk_analysis_run_conversation_run FOREIGN KEY (run_id) REFERENCES analysis_run (id) ON DELETE CASCADE,
    CONSTRAINT fk_analysis_run_conversation_conversation FOREIGN KEY (conversation_id)
        REFERENCES conversation (id) ON DELETE CASCADE
);

CREATE INDEX idx_analysis_run_conversation_conversation ON analysis_run_conversation (conversation_id);

-- 모델 하나의 결과. 호출하지 않은 모델(키·모델 미설정)도 NOT_CONFIGURED로 남겨 몇 개 모델로 비교했는지 보여 준다
CREATE TABLE analysis_model_result (
    id                     BIGINT         GENERATED BY DEFAULT AS IDENTITY,
    run_id                 BIGINT         NOT NULL,
    -- GPT / CLAUDE / GEMINI
    provider               VARCHAR(20)    NOT NULL,
    model                  VARCHAR(100)   NULL,
    -- SUCCEEDED / FAILED / INVALID_OUTPUT / NOT_CONFIGURED
    status                 VARCHAR(20)    NOT NULL,
    error_code             VARCHAR(40)    NULL,
    -- 모델이 돌려준 글 그대로 (검증 전 원본, 최대 60,000자)
    raw_output             VARCHAR(60000) NULL,
    input_tokens           INTEGER        NULL,
    output_tokens          INTEGER        NULL,
    attempt_count          INTEGER        NOT NULL,
    latency_ms             BIGINT         NULL,
    -- 검증에서 버린 근거 수 (보낸 적 없는 메시지 id, 말한 사람이 맞지 않는 근거 등)
    dropped_evidence_count INTEGER        NOT NULL,
    created_at             TIMESTAMP(6)   NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT uk_analysis_model_result UNIQUE (run_id, provider),
    CONSTRAINT fk_analysis_model_result_run FOREIGN KEY (run_id) REFERENCES analysis_run (id) ON DELETE CASCADE
);

