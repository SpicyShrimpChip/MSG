-- ==================== 퀴즈·사전사후평가·확인 퀴즈 ====================
-- 채점과 점수 합산은 서버 코드가 하고, AI는 문제·해설·피드백만 쓴다.
-- 퀴즈는 만든 본인만 본다. 회원·과목·자료를 지우면 그 퀴즈와 제출 기록도 함께 지워진다

-- 퀴즈. 일반 퀴즈(학습 모드 3가지)·모의시험·사전·사후평가·개념 확인 퀴즈가 모두 이 표다
CREATE TABLE quiz (
    id                    BIGINT       GENERATED BY DEFAULT AS IDENTITY,
    user_id               BIGINT       NOT NULL,
    course_id             BIGINT       NOT NULL,
    -- 이 퀴즈를 만든 자료. 약점 개념으로 만든 퀴즈처럼 자료가 없으면 NULL
    material_id           BIGINT       NULL,
    title                 VARCHAR(100) NOT NULL,
    created_at            TIMESTAMP(6) NOT NULL,
    -- 학습 모드: EXAM_PREP(시험 대비) / SELF_DEVELOPMENT(자기개발) / WORK(업무 활용)
    mode                  VARCHAR(20)  NULL,
    difficulty            VARCHAR(10)  NULL,
    -- 업무 활용 퀴즈를 만들 때 쓴 직무. 고르지 않았으면 NULL(일반 실무)
    job_field             VARCHAR(40)  NULL,
    job_field_other       VARCHAR(30)  NULL,
    -- 사용자가 적은 시험 범위 (선택)
    exam_scope            VARCHAR(200) NULL,
    -- 문제를 만든 AI 제공사·모델. 사람이 넣은 퀴즈는 NULL
    generated_provider    VARCHAR(10)  NULL,
    generated_model       VARCHAR(100) NULL,
    -- 모의시험(시험 대비 모드에서 범위 전체를 실제 시험처럼)
    mock_exam             BOOLEAN      DEFAULT FALSE NOT NULL,
    -- PRE(사전평가) / POST(사후평가). 일반 퀴즈는 NULL
    assessment_kind       VARCHAR(10)  NULL,
    -- 사후평가가 비교하는 사전평가. 사전평가를 지우면 연결만 끊긴다
    pre_assessment_id     BIGINT       NULL,
    -- 학습자료 본문(발췌)을 AI에 보내 문제를 만들었는지
    material_content_used BOOLEAN      DEFAULT FALSE NOT NULL,
    -- 평가 문제의 개념 출처: MATERIAL(자료에서 뽑은 개념) / COURSE(과목 키워드). 일반 퀴즈는 NULL
    concept_source        VARCHAR(10)  NULL,
    -- 개념 확인 퀴즈: 자료(material_id)의 개념 하나만 다루는 퀴즈. 일반 퀴즈·모의시험·사전·사후평가는 NULL
    check_concept_key     VARCHAR(20)  NULL,
    check_concept_name    VARCHAR(20)  NULL,
    PRIMARY KEY (id),
    CONSTRAINT fk_quiz_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT fk_quiz_course FOREIGN KEY (course_id) REFERENCES course (id) ON DELETE CASCADE,
    CONSTRAINT fk_quiz_material FOREIGN KEY (material_id) REFERENCES material (id) ON DELETE CASCADE,
    CONSTRAINT fk_quiz_pre_assessment FOREIGN KEY (pre_assessment_id) REFERENCES quiz (id) ON DELETE SET NULL
);

CREATE INDEX idx_quiz_user ON quiz (user_id);
CREATE INDEX idx_quiz_course ON quiz (course_id);
CREATE INDEX idx_quiz_material ON quiz (material_id);

-- 문제. 정답(번호·허용 답·모범 답안)은 제출 뒤 결과에만 내보낸다 (풀기 화면 응답에는 넣지 않는다)
CREATE TABLE quiz_question (
    id                   BIGINT        GENERATED BY DEFAULT AS IDENTITY,
    quiz_id              BIGINT        NOT NULL,
    sort_order           INTEGER       NOT NULL,
    content              VARCHAR(1000) NOT NULL,
    -- 객관식 정답 보기 순서(quiz_choice.sort_order, 0부터). 주관식·서술형은 NULL
    correct_choice_index INTEGER       NULL,
    -- AI가 쓴 해설. 없으면 NULL
    ai_explanation       VARCHAR(2000) NULL,
    -- MULTIPLE_CHOICE / SHORT_ANSWER / ESSAY
    question_type        VARCHAR(20)   DEFAULT 'MULTIPLE_CHOICE' NOT NULL,
    -- 업무 활용 문제의 상황·사용자 역할 (다른 모드는 NULL)
    scenario             VARCHAR(2000) NULL,
    work_role            VARCHAR(200)  NULL,
    -- 답변 작성 안내 (주관식·서술형)
    answer_guide         VARCHAR(500)  NULL,
    -- 참고 모범 답안 (AI). 제출 뒤 결과에만 내보낸다
    model_answer         VARCHAR(4000) NULL,
    PRIMARY KEY (id),
    CONSTRAINT uk_quiz_question_order UNIQUE (quiz_id, sort_order),
    CONSTRAINT fk_quiz_question_quiz FOREIGN KEY (quiz_id) REFERENCES quiz (id) ON DELETE CASCADE
);

CREATE TABLE quiz_choice (
    question_id BIGINT       NOT NULL,
    sort_order  INTEGER      NOT NULL,
    content     VARCHAR(500) NOT NULL,
    PRIMARY KEY (question_id, sort_order),
    CONSTRAINT fk_quiz_choice_question FOREIGN KEY (question_id) REFERENCES quiz_question (id) ON DELETE CASCADE
);

-- 문제가 다루는 개념. concept_key는 학습 분석의 concept_key와 같은 규칙(과목 키워드를 소문자로 맞춘 값)이다
CREATE TABLE quiz_question_concept (
    question_id  BIGINT      NOT NULL,
    sort_order   INTEGER     NOT NULL,
    concept_key  VARCHAR(20) NOT NULL,
    concept_name VARCHAR(20) NOT NULL,
    PRIMARY KEY (question_id, sort_order),
    CONSTRAINT fk_quiz_question_concept_question FOREIGN KEY (question_id)
        REFERENCES quiz_question (id) ON DELETE CASCADE
);

-- 제출 한 번. 같은 퀴즈를 여러 번 풀 수 있고, 목록·결과 화면은 가장 최근 제출(id가 가장 큰 것)을 쓴다
CREATE TABLE quiz_submission (
    id            BIGINT       GENERATED BY DEFAULT AS IDENTITY,
    quiz_id       BIGINT       NOT NULL,
    user_id       BIGINT       NOT NULL,
    correct_count INTEGER      NOT NULL,
    total_count   INTEGER      NOT NULL,
    submitted_at  TIMESTAMP(6) NOT NULL,
    -- 점수는 서버 코드가 합산한다
    score         INTEGER      DEFAULT 0 NOT NULL,
    max_score     INTEGER      DEFAULT 0 NOT NULL,
    -- AI 채점을 기다리는(모델 없음·동의 없음·실패) 답 수, AI 판단이 엇갈려 확인이 필요한 답 수
    pending_count INTEGER      DEFAULT 0 NOT NULL,
    review_count  INTEGER      DEFAULT 0 NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT fk_quiz_submission_quiz FOREIGN KEY (quiz_id) REFERENCES quiz (id) ON DELETE CASCADE,
    CONSTRAINT fk_quiz_submission_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE
);

CREATE INDEX idx_quiz_submission_quiz ON quiz_submission (quiz_id, id);
CREATE INDEX idx_quiz_submission_user ON quiz_submission (user_id);

-- 문제별 채점 결과. 답하지 않은 객관식 문제는 choice_index -1(틀림)로 남긴다
CREATE TABLE quiz_answer (
    id              BIGINT        GENERATED BY DEFAULT AS IDENTITY,
    submission_id   BIGINT        NOT NULL,
    question_id     BIGINT        NOT NULL,
    choice_index    INTEGER       NOT NULL,
    correct         BOOLEAN       NOT NULL,
    -- 주관식·서술형 답 (객관식은 NULL, choice_index는 -1)
    text_answer     VARCHAR(5000) NULL,
    score           INTEGER       DEFAULT 0 NOT NULL,
    max_score       INTEGER       DEFAULT 1 NOT NULL,
    -- GRADED / NEEDS_REVIEW(모델 판단이 엇갈림) / PENDING(AI 채점 대기)
    grading_status  VARCHAR(20)   DEFAULT 'GRADED' NOT NULL,
    -- 채점 방법: CODE(객관식) / MATCH(허용 답 일치) / AI
    grading_method  VARCHAR(10)   DEFAULT 'CODE' NOT NULL,
    -- 채점 대기·확인 필요 이유 코드 (NOT_CONFIGURED, NO_CONSENT, LIMIT_EXCEEDED, MODEL_FAILED, DISAGREEMENT, SINGLE_MODEL)
    grading_note    VARCHAR(30)   NULL,
    -- AI를 부른 모델 수 / 판단을 돌려준 모델 수
    ai_called_count INTEGER       DEFAULT 0 NOT NULL,
    ai_judged_count INTEGER       DEFAULT 0 NOT NULL,
    -- AI 피드백 (서술형). 점수와 따로 둔다
    ai_strengths    VARCHAR(1000) NULL,
    ai_missing      VARCHAR(1000) NULL,
    ai_improvements VARCHAR(1000) NULL,
    ai_practical    VARCHAR(1000) NULL,
    PRIMARY KEY (id),
    CONSTRAINT uk_quiz_answer UNIQUE (submission_id, question_id),
    CONSTRAINT fk_quiz_answer_submission FOREIGN KEY (submission_id)
        REFERENCES quiz_submission (id) ON DELETE CASCADE,
    CONSTRAINT fk_quiz_answer_question FOREIGN KEY (question_id)
        REFERENCES quiz_question (id) ON DELETE CASCADE
);

CREATE INDEX idx_quiz_answer_question ON quiz_answer (question_id);

-- AI가 제안한 다음 학습 개념 (자기개발 모드). 실제 풀이 결과와 섞지 않으려고 따로 둔다
CREATE TABLE quiz_suggestion (
    quiz_id    BIGINT       NOT NULL,
    sort_order INTEGER      NOT NULL,
    -- next: 다음 단계 / prerequisite: 보완할 선수 지식 / related: 연관 분야
    kind       VARCHAR(20)  NOT NULL,
    concept    VARCHAR(40)  NOT NULL,
    reason     VARCHAR(300) NULL,
    PRIMARY KEY (quiz_id, sort_order),
    CONSTRAINT fk_quiz_suggestion_quiz FOREIGN KEY (quiz_id) REFERENCES quiz (id) ON DELETE CASCADE
);

-- 퀴즈 만들기 요청 기록. 같은 요청(request_key)을 두 번 보내도 한 번만 만들고, 실패 이유와 호출량을 남긴다
CREATE TABLE quiz_generation (
    id               BIGINT       GENERATED BY DEFAULT AS IDENTITY,
    user_id          BIGINT       NOT NULL,
    course_id        BIGINT       NOT NULL,
    -- 프론트가 만든 요청 키 (같은 버튼을 두 번 눌러도 퀴즈가 하나만 생기게)
    request_key      VARCHAR(64)  NOT NULL,
    mode             VARCHAR(20)  NOT NULL,
    -- 고른 문제 유형 (쉼표로 이음, 예: MULTIPLE_CHOICE,ESSAY)
    question_types   VARCHAR(60)  NOT NULL,
    question_count   INTEGER      NOT NULL,
    difficulty       VARCHAR(10)  NOT NULL,
    -- RUNNING / SUCCEEDED / FAILED / TIMED_OUT
    status           VARCHAR(20)  NOT NULL,
    -- 실패 이유 코드 (사용자 문구는 코드에서 만든다). 성공이면 NULL
    error_code       VARCHAR(30)  NULL,
    provider         VARCHAR(10)  NULL,
    model            VARCHAR(100) NULL,
    -- 만든 퀴즈. 퀴즈를 지우면 기록만 남는다
    quiz_id          BIGINT       NULL,
    input_tokens     INTEGER      NULL,
    output_tokens    INTEGER      NULL,
    attempts         INTEGER      DEFAULT 0 NOT NULL,
    created_at       TIMESTAMP(6) NOT NULL,
    finished_at      TIMESTAMP(6) NULL,
    -- 이 시각이 지나면 그 요청은 끝난 것으로 보고(TIMED_OUT) 늦게 온 모델 답은 저장하지 않는다
    deadline_at      TIMESTAMP(6) NULL,
    PRIMARY KEY (id),
    CONSTRAINT uk_quiz_generation_request UNIQUE (user_id, request_key),
    CONSTRAINT fk_quiz_generation_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT fk_quiz_generation_course FOREIGN KEY (course_id) REFERENCES course (id) ON DELETE CASCADE,
    CONSTRAINT fk_quiz_generation_quiz FOREIGN KEY (quiz_id) REFERENCES quiz (id) ON DELETE SET NULL
);

CREATE INDEX idx_quiz_generation_user ON quiz_generation (user_id, created_at);

-- 주관식 허용 답 (여러 표현). 제출 뒤 결과에만 내보낸다
