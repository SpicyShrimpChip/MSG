    CONSTRAINT fk_concept_mastery_course FOREIGN KEY (course_id) REFERENCES course (id) ON DELETE CASCADE,
    CONSTRAINT fk_concept_mastery_run FOREIGN KEY (analysis_run_id) REFERENCES analysis_run (id) ON DELETE CASCADE
);

CREATE INDEX idx_concept_mastery_course ON concept_mastery (user_id, course_id, concept_key, id);

-- ==================== AI 이용 한도·재가입 제한 ====================

-- 서비스 전체에서 하루에 부른 AI 모델 호출 수 (비용 상한, app.ai-daily-limit).
-- 사용자·과목과 연결하지 않는다: 과목 삭제·탈퇴·재가입으로 줄어들지 않게 한다. 개인정보는 없다.
-- 날짜는 app.ai-daily-limit.zone(기본 한국 시간) 기준, 하루에 한 줄
CREATE TABLE ai_daily_usage (
    usage_date DATE PRIMARY KEY,
    call_count INT  NOT NULL
);

-- 탈퇴 뒤 재가입 제한 (app.rejoin). 탈퇴·재가입을 반복해 사용자별 AI 이용 한도를 우회하는 것을 막는다.
-- 이메일 원문은 남기지 않고, 정규화한 이메일에 비밀 키(REJOIN_HASH_SECRET)로 건 HMAC-SHA256 값(16진수 64자)만 둔다.
-- users와 연결하지 않는다(탈퇴로 users 행은 이미 지워진다). 재가입 가능 시각이 지나면 주기 작업이 지운다
CREATE TABLE withdrawn_account (
    email_hash        VARCHAR(64)  PRIMARY KEY,
    withdrawn_at      TIMESTAMP(6) NOT NULL,
    rejoin_allowed_at TIMESTAMP(6) NOT NULL
);

CREATE INDEX idx_withdrawn_account_rejoin_allowed_at ON withdrawn_account (rejoin_allowed_at);

-- 사용자별 24시간 AI 이용 횟수를 세는 기록 (분석 시작·퀴즈 만들기·AI 채점 실행).
-- analysis_run·quiz_generation·quiz_grading_run 행은 과목·제출에 CASCADE로 달려 있어 과목을 지우면 하루 한도가 다시 차므로,
-- 이 표는 users에만 연결한다(탈퇴 때만 지운다). 개인정보·본문은 없고, 하루가 지난 행은 주기 작업이 지운다(UserAiUsage)
CREATE TABLE user_ai_usage (
    id         BIGINT       GENERATED BY DEFAULT AS IDENTITY,
    user_id    BIGINT       NOT NULL,
    -- ANALYSIS_RUN / QUIZ_GENERATION / QUIZ_GRADING
    kind       VARCHAR(20)  NOT NULL,
    created_at TIMESTAMP(6) NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT fk_user_ai_usage_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE
);

CREATE INDEX idx_user_ai_usage_user_kind ON user_ai_usage (user_id, kind, created_at);
CREATE INDEX idx_user_ai_usage_created_at ON user_ai_usage (created_at);
