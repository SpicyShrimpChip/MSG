-- 서술형 채점 기준과 배점. 배점 합이 그 문제의 만점이다
CREATE TABLE quiz_question_rubric (
    question_id BIGINT       NOT NULL,
    sort_order  INTEGER      NOT NULL,
    criterion   VARCHAR(200) NOT NULL,
    points      INTEGER      NOT NULL,
    PRIMARY KEY (question_id, sort_order),
    CONSTRAINT fk_quiz_rubric_question FOREIGN KEY (question_id)
        REFERENCES quiz_question (id) ON DELETE CASCADE
);

-- 서술형 채점 기준별 결과. 모델마다 따로 판단하고 다수 의견(코드)으로 정한 수준과 점수(코드)를 둔다
CREATE TABLE quiz_answer_rubric_score (
    answer_id   BIGINT       NOT NULL,
    sort_order  INTEGER      NOT NULL,
    -- MET / PARTIAL / NOT_MET. 다수 의견이 없으면 NULL
    level       VARCHAR(10)  NULL,
    points      INTEGER      NOT NULL,
    agree_count INTEGER      NOT NULL,
    judged_count INTEGER     NOT NULL,
    -- 다수 의견을 낸 모델 하나의 근거 (AI)
    reason      VARCHAR(500) NULL,
    PRIMARY KEY (answer_id, sort_order),
    CONSTRAINT fk_quiz_rubric_score_answer FOREIGN KEY (answer_id)
        REFERENCES quiz_answer (id) ON DELETE CASCADE
);

-- 제출 한 번의 AI 채점 실행(처음 채점·다시 채점). 모델을 부르기 전에 이 행을 만들어(예약) 24시간 한도를 세고,
-- 같은 제출의 채점이 진행 중이면 다른 요청을 막는다. 마감 시각이 지나면 끝난 것으로 본다
CREATE TABLE quiz_grading_run (
    id            BIGINT       GENERATED BY DEFAULT AS IDENTITY,
    user_id       BIGINT       NOT NULL,
    submission_id BIGINT       NOT NULL,
    -- INITIAL(제출할 때) / REGRADE(다시 채점)
    kind          VARCHAR(10)  NOT NULL,
    -- RUNNING / SUCCEEDED / FAILED / TIMED_OUT
    status        VARCHAR(20)  NOT NULL,
    -- 이번 실행에서 채점한 답 수
    answer_count  INTEGER      NOT NULL,
    created_at    TIMESTAMP(6) NOT NULL,
    deadline_at   TIMESTAMP(6) NOT NULL,
    finished_at   TIMESTAMP(6) NULL,
    PRIMARY KEY (id),
    CONSTRAINT fk_quiz_grading_run_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT fk_quiz_grading_run_submission FOREIGN KEY (submission_id)
        REFERENCES quiz_submission (id) ON DELETE CASCADE
);

CREATE INDEX idx_quiz_grading_run_user ON quiz_grading_run (user_id, created_at);
CREATE INDEX idx_quiz_grading_run_submission ON quiz_grading_run (submission_id, status);

-- 퀴즈 만들기·AI 채점·개념 설명에서 모델을 부른 기록 한 줄 = 모델 하나를 한 번 부른 것(재시도는 attempts로 센다).
-- 실패한 호출도 비용이 들 수 있어 남긴다. 요청·응답 글은 남기지 않는다.
-- 퀴즈 만들기·채점 실행이 지워져도 기록은 남기고 연결만 끊는다(실제 모델 요청 수 상한에 쓴다). 탈퇴 때는 함께 지워진다
CREATE TABLE quiz_ai_call (
    id              BIGINT       GENERATED BY DEFAULT AS IDENTITY,
    user_id         BIGINT       NOT NULL,
    -- GENERATION / GRADING 등 부른 목적
    purpose         VARCHAR(20)  NOT NULL,
    generation_id   BIGINT       NULL,
