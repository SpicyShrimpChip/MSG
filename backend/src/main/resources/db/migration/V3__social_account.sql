-- 소셜 로그인(카카오) 계정 연결. 가입을 마친 사용자만 여기에 한 줄이 생긴다(가입 마무리 전에는 카카오 정보를 저장하지 않는다).
-- 카카오로만 가입한 사용자는 비밀번호가 없으므로 password_hash를 비워 둘 수 있게 한다(비밀번호 로그인은 늘 실패한다)
ALTER TABLE users ALTER COLUMN password_hash DROP NOT NULL;

CREATE TABLE user_social_account (
    id               BIGINT       GENERATED BY DEFAULT AS IDENTITY,
    user_id          BIGINT       NOT NULL,
    -- 제공사 이름 (지금은 KAKAO만)
    provider         VARCHAR(20)  NOT NULL,
    -- 제공사의 회원번호 (카카오 회원번호). 이메일·닉네임은 여기에 두지 않는다
    provider_user_id VARCHAR(64)  NOT NULL,
    created_at       TIMESTAMP(6) NOT NULL,
    PRIMARY KEY (id),
    -- 카카오 계정 하나는 사용자 한 명에게만 연결된다
    CONSTRAINT uk_user_social_account_provider_user UNIQUE (provider, provider_user_id),
    -- 사용자 한 명에게 같은 제공사는 하나만 연결된다
    CONSTRAINT uk_user_social_account_user_provider UNIQUE (user_id, provider),
    -- 탈퇴하면 연결도 함께 지운다 (카카오 연결 끊기는 탈퇴 커밋 뒤에 따로 부른다)
    CONSTRAINT fk_user_social_account_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE
);
