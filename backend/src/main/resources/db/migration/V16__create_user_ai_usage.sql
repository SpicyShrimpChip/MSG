-- 사용자별 24시간 AI 이용 횟수를 세는 기록 (분석 시작·퀴즈 만들기·AI 채점 실행)
-- 전에는 analysis_run·quiz_generation·quiz_grading_run 행을 셌는데, 이 행들은 과목·제출에 CASCADE로 달려 있어
-- 과목을 지우면 기록도 지워지고 하루 한도가 다시 차는 문제가 있었다. 이 표는 users에만 연결한다(탈퇴 때만 지운다).
-- 개인정보·본문은 없고, 하루가 지난 행은 주기 작업이 지운다(UserAiUsage)
CREATE TABLE user_ai_usage (
    id         BIGINT       GENERATED BY DEFAULT AS IDENTITY,
    user_id    BIGINT       NOT NULL,
    -- ANALYSIS_RUN / QUIZ_GENERATION / QUIZ_GRADING
    kind       VARCHAR(20)  NOT NULL,
    created_at TIMESTAMP(6) NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT fk_user_ai_usage_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE
);

CREATE INDEX idx_user_ai_usage_user_kind ON user_ai_usage (user_id, kind, created_at);
CREATE INDEX idx_user_ai_usage_created_at ON user_ai_usage (created_at);

-- 지금까지의 기록을 옮겨 배포 직후에도 오늘 쓴 횟수가 이어지게 한다
INSERT INTO user_ai_usage (user_id, kind, created_at)
    SELECT user_id, 'ANALYSIS_RUN', created_at FROM analysis_run;
INSERT INTO user_ai_usage (user_id, kind, created_at)
    SELECT user_id, 'QUIZ_GENERATION', created_at FROM quiz_generation;
INSERT INTO user_ai_usage (user_id, kind, created_at)
    SELECT user_id, 'QUIZ_GRADING', created_at FROM quiz_grading_run;

-- 모델 호출 기록(실제 모델 요청 수 상한, 개념 설명 횟수에 쓴다)도 퀴즈 만들기·채점 실행이 지워질 때 같이 지워지지 않게 한다.
-- 연결만 끊고(NULL) 기록은 남긴다. 사용자 탈퇴 때는 fk_quiz_ai_call_user로 지워진다
ALTER TABLE quiz_ai_call DROP CONSTRAINT fk_quiz_ai_call_generation;
ALTER TABLE quiz_ai_call ADD CONSTRAINT fk_quiz_ai_call_generation FOREIGN KEY (generation_id)
    REFERENCES quiz_generation (id) ON DELETE SET NULL;
ALTER TABLE quiz_ai_call DROP CONSTRAINT fk_quiz_ai_call_grading_run;
ALTER TABLE quiz_ai_call ADD CONSTRAINT fk_quiz_ai_call_grading_run FOREIGN KEY (grading_run_id)
    REFERENCES quiz_grading_run (id) ON DELETE SET NULL;
