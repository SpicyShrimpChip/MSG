-- AI 퀴즈 처리 동의(대화 분석 동의와 분리), AI 채점 실행 예약, 모델 호출 기록, 생성 마감 시각, 모의시험 표시.
-- 기존 행은 지우거나 바꾸지 않는다. 기존 회원은 AI 퀴즈 처리에 동의하지 않은 상태(FALSE)로 둔다(자동 동의 금지).
-- H2(PostgreSQL 모드)와 PostgreSQL에서 모두 돌도록 DB 전용 문법을 쓰지 않는다

-- ---------- 회원: AI 퀴즈 처리 동의(선택) ----------
-- 퀴즈 만들기·주관식·서술형 AI 채점 때 과목 이름·개념·시험 범위·직무·학습자 답을 외부 AI로 보내는 데 대한 동의.
-- AI 대화 분석 동의(ai_analysis_consent)와 목적·항목이 달라 따로 받는다
ALTER TABLE users ADD COLUMN ai_quiz_consent BOOLEAN DEFAULT FALSE NOT NULL;
ALTER TABLE users ADD COLUMN ai_quiz_consented_at TIMESTAMP(6) NULL;

-- ---------- 퀴즈 만들기: 마감 시각 ----------
-- 이 시각이 지나면 그 요청은 끝난 것으로 보고(TIMED_OUT) 늦게 온 모델 답은 저장하지 않는다. V7 행은 NULL
ALTER TABLE quiz_generation ADD COLUMN deadline_at TIMESTAMP(6) NULL;

-- 모의시험(시험 대비 모드에서 범위 전체를 실제 시험처럼). 기존 퀴즈는 FALSE
ALTER TABLE quiz ADD COLUMN mock_exam BOOLEAN DEFAULT FALSE NOT NULL;

-- ---------- AI 채점 실행 ----------
-- 제출 한 번의 AI 채점 실행(처음 채점·다시 채점). 모델을 부르기 전에 이 행을 만들어(예약) 24시간 한도를 세고,
-- 같은 제출의 채점이 진행 중이면 다른 요청을 막는다. 마감 시각이 지나면 끝난 것으로 본다
CREATE TABLE quiz_grading_run (
    id            BIGINT       GENERATED BY DEFAULT AS IDENTITY,
    user_id       BIGINT       NOT NULL,
    submission_id BIGINT       NOT NULL,
    -- INITIAL(제출할 때) / REGRADE(다시 채점)
    kind          VARCHAR(10)  NOT NULL,
    -- RUNNING / SUCCEEDED / FAILED / TIMED_OUT
    status        VARCHAR(20)  NOT NULL,
    -- 이번 실행에서 채점한 답 수
    answer_count  INTEGER      NOT NULL,
    created_at    TIMESTAMP(6) NOT NULL,
    deadline_at   TIMESTAMP(6) NOT NULL,
    finished_at   TIMESTAMP(6) NULL,
    PRIMARY KEY (id),
    CONSTRAINT fk_quiz_grading_run_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT fk_quiz_grading_run_submission FOREIGN KEY (submission_id)
        REFERENCES quiz_submission (id) ON DELETE CASCADE
);

CREATE INDEX idx_quiz_grading_run_user ON quiz_grading_run (user_id, created_at);
CREATE INDEX idx_quiz_grading_run_submission ON quiz_grading_run (submission_id, status);

-- ---------- 모델 호출 기록 ----------
-- 퀴즈 만들기·AI 채점에서 모델을 부른 기록 한 줄 = 모델 하나를 한 번 부른 것(재시도는 attempts로 센다).
-- 실패한 호출도 비용이 들 수 있어 남긴다. 요청·응답 글은 남기지 않는다
CREATE TABLE quiz_ai_call (
    id              BIGINT       GENERATED BY DEFAULT AS IDENTITY,
    user_id         BIGINT       NOT NULL,
    -- GENERATION / GRADING
    purpose         VARCHAR(20)  NOT NULL,
    generation_id   BIGINT       NULL,
    grading_run_id  BIGINT       NULL,
    provider        VARCHAR(10)  NOT NULL,
    model           VARCHAR(100) NULL,
    -- 실제로 보낸 HTTP 요청 수 (재시도 포함)
    attempts        INTEGER      NOT NULL,
    -- SUCCEEDED / FAILED / INVALID_OUTPUT / TIMED_OUT
    outcome         VARCHAR(20)  NOT NULL,
    error_code      VARCHAR(30)  NULL,
    input_tokens    INTEGER      NULL,
    output_tokens   INTEGER      NULL,
    latency_ms      BIGINT       NOT NULL,
    created_at      TIMESTAMP(6) NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT fk_quiz_ai_call_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT fk_quiz_ai_call_generation FOREIGN KEY (generation_id)
        REFERENCES quiz_generation (id) ON DELETE CASCADE,
    CONSTRAINT fk_quiz_ai_call_grading_run FOREIGN KEY (grading_run_id)
        REFERENCES quiz_grading_run (id) ON DELETE CASCADE
);

CREATE INDEX idx_quiz_ai_call_user ON quiz_ai_call (user_id, created_at);
