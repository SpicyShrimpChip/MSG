-- 외부 AI(ChatGPT·Claude)에서 가져온 대화. 프론트가 브라우저에서 개인정보를 가린 뒤 보낸 글만 저장한다
-- (원본 내보내기 파일은 서버로 오지 않는다). 서버도 개인정보 패턴을 한 번 더 검사하고, 남아 있으면 저장하지 않는다.
-- H2(PostgreSQL 모드)와 PostgreSQL에서 모두 돌도록 DB 전용 문법을 쓰지 않는다

-- 가져오기 작업 하나 = 사용자가 "보내기"를 한 번 누른 것. 프론트는 대화를 과목별·크기별로 나눠 여러 요청으로 보내고,
-- 모든 요청(request_count개)을 받아야 COMPLETED가 된다. AI 분석은 COMPLETED 작업의 대화만 쓴다
CREATE TABLE conversation_import (
    id               BIGINT       GENERATED BY DEFAULT AS IDENTITY,
    user_id          BIGINT       NOT NULL,
    -- 프론트가 만든 작업 id(UUID). 같은 id로 다시 보내면 같은 작업으로 이어 받는다
    client_import_id VARCHAR(36)  NOT NULL,
    request_count    INTEGER      NOT NULL,
    -- IN_PROGRESS / COMPLETED
    status           VARCHAR(20)  NOT NULL,
    created_at       TIMESTAMP(6) NOT NULL,
    completed_at     TIMESTAMP(6) NULL,
    PRIMARY KEY (id),
    CONSTRAINT uk_conversation_import_client UNIQUE (user_id, client_import_id),
    CONSTRAINT fk_conversation_import_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE
);

-- 작업에서 이미 받은 요청 번호. 같은 요청을 다시 받으면 저장하지 않고 같은 결과를 돌려준다
CREATE TABLE conversation_import_request (
    id                 BIGINT       GENERATED BY DEFAULT AS IDENTITY,
    import_id          BIGINT       NOT NULL,
    request_index      INTEGER      NOT NULL,
    conversation_count INTEGER      NOT NULL,
    created_at         TIMESTAMP(6) NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT uk_conversation_import_request UNIQUE (import_id, request_index),
    CONSTRAINT fk_conversation_import_request_import FOREIGN KEY (import_id)
        REFERENCES conversation_import (id) ON DELETE CASCADE
);

-- 대화 하나. 긴 대화는 조각(part)으로 나뉘어 여러 요청으로 올 수 있고, 조각을 모두 받아야 완성된다
CREATE TABLE conversation (
    id                  BIGINT       GENERATED BY DEFAULT AS IDENTITY,
    user_id             BIGINT       NOT NULL,
    course_id           BIGINT       NOT NULL,
    -- 이 대화를 마지막으로 보낸 가져오기 작업. 그 작업이 COMPLETED이고 조각을 모두 받았을 때만 분석에 쓴다
    import_id           BIGINT       NOT NULL,
    -- CHATGPT / CLAUDE
    source              VARCHAR(20)  NOT NULL,
    -- 내보내기 파일 안의 대화 id (나눠 보낸 대화는 원래 id). 같은 사용자·서비스에서 한 번만 저장한다
    client_id           VARCHAR(200) NOT NULL,
    title               VARCHAR(500) NOT NULL,
    -- 외부 서비스에서 대화를 시작한 시각 (파일에 없으면 NULL)
    source_created_at   TIMESTAMP(6) NULL,
    part_count          INTEGER      NOT NULL,
    received_part_count INTEGER      NOT NULL,
    message_count       INTEGER      NOT NULL,
    created_at          TIMESTAMP(6) NOT NULL,
    updated_at          TIMESTAMP(6) NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT uk_conversation_client UNIQUE (user_id, source, client_id),
    CONSTRAINT fk_conversation_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
    -- 과목을 지우면 그 과목에 가져온 대화도 지운다 (학습자료와 같은 규칙)
    CONSTRAINT fk_conversation_course FOREIGN KEY (course_id) REFERENCES course (id) ON DELETE CASCADE,
    -- 작업 행은 따로 지우지 않는다. 회원 탈퇴 때 users에서 함께 지워지는 순서와 상관없게 CASCADE로 둔다
    CONSTRAINT fk_conversation_import FOREIGN KEY (import_id) REFERENCES conversation_import (id) ON DELETE CASCADE
);

CREATE INDEX idx_conversation_user_created ON conversation (user_id, created_at);
CREATE INDEX idx_conversation_course ON conversation (course_id);
CREATE INDEX idx_conversation_import ON conversation (import_id);

-- 받은 조각. 조각 없이 온 대화는 1번 조각 하나로 기록한다
CREATE TABLE conversation_part (
    id              BIGINT       GENERATED BY DEFAULT AS IDENTITY,
    conversation_id BIGINT       NOT NULL,
    part_index      INTEGER      NOT NULL,
    message_count   INTEGER      NOT NULL,
    created_at      TIMESTAMP(6) NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT uk_conversation_part UNIQUE (conversation_id, part_index),
    CONSTRAINT fk_conversation_part_conversation FOREIGN KEY (conversation_id)
        REFERENCES conversation (id) ON DELETE CASCADE
);

-- 메시지. 대화 안의 순서는 (part_index, seq)다.
-- 20,000자가 넘는 메시지는 프론트가 나눠 보내고, 이어지는 글이 다음 메시지에 있으면 continued가 TRUE다
CREATE TABLE conversation_message (
    id              BIGINT         GENERATED BY DEFAULT AS IDENTITY,
    conversation_id BIGINT         NOT NULL,
    part_index      INTEGER        NOT NULL,
    seq             INTEGER        NOT NULL,
    -- USER / ASSISTANT
    role            VARCHAR(10)    NOT NULL,
    content         VARCHAR(20000) NOT NULL,
    continued       BOOLEAN        NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT uk_conversation_message UNIQUE (conversation_id, part_index, seq),
    CONSTRAINT fk_conversation_message_conversation FOREIGN KEY (conversation_id)
        REFERENCES conversation (id) ON DELETE CASCADE
);
