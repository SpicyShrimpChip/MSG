ALTER TABLE quiz_answer ADD COLUMN text_answer VARCHAR(5000) NULL;
ALTER TABLE quiz_answer ADD COLUMN score INTEGER DEFAULT 0 NOT NULL;
ALTER TABLE quiz_answer ADD COLUMN max_score INTEGER DEFAULT 1 NOT NULL;
