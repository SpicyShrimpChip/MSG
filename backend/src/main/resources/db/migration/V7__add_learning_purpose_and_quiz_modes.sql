ALTER TABLE quiz_answer ADD COLUMN grading_method VARCHAR(10) DEFAULT 'CODE' NOT NULL;
-- 채점 대기·확인 필요 이유 코드 (NOT_CONFIGURED, NO_CONSENT, LIMIT_EXCEEDED, MODEL_FAILED, DISAGREEMENT, SINGLE_MODEL)
ALTER TABLE quiz_answer ADD COLUMN grading_note VARCHAR(30) NULL;
-- AI를 부른 모델 수 / 판단을 돌려준 모델 수
ALTER TABLE quiz_answer ADD COLUMN ai_called_count INTEGER DEFAULT 0 NOT NULL;
ALTER TABLE quiz_answer ADD COLUMN ai_judged_count INTEGER DEFAULT 0 NOT NULL;
-- AI 피드백 (서술형). 점수와 따로 둔다
ALTER TABLE quiz_answer ADD COLUMN ai_strengths VARCHAR(1000) NULL;
ALTER TABLE quiz_answer ADD COLUMN ai_missing VARCHAR(1000) NULL;
ALTER TABLE quiz_answer ADD COLUMN ai_improvements VARCHAR(1000) NULL;
ALTER TABLE quiz_answer ADD COLUMN ai_practical VARCHAR(1000) NULL;
UPDATE quiz_answer SET score = 1 WHERE correct = TRUE;

-- 서술형 채점 기준별 결과. 모델마다 따로 판단하고 다수 의견(코드)으로 정한 수준과 점수(코드)를 둔다
CREATE TABLE quiz_answer_rubric_score (
    answer_id   BIGINT       NOT NULL,
    sort_order  INTEGER      NOT NULL,
    -- MET / PARTIAL / NOT_MET. 다수 의견이 없으면 NULL
    level       VARCHAR(10)  NULL,
    points      INTEGER      NOT NULL,
    agree_count INTEGER      NOT NULL,
    judged_count INTEGER     NOT NULL,
    -- 다수 의견을 낸 모델 하나의 근거 (AI)
    reason      VARCHAR(500) NULL,
    PRIMARY KEY (answer_id, sort_order),
    CONSTRAINT fk_quiz_rubric_score_answer FOREIGN KEY (answer_id)
        REFERENCES quiz_answer (id) ON DELETE CASCADE
);
