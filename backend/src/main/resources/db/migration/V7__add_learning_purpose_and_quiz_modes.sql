ALTER TABLE quiz_submission ADD COLUMN pending_count INTEGER DEFAULT 0 NOT NULL;
ALTER TABLE quiz_submission ADD COLUMN review_count INTEGER DEFAULT 0 NOT NULL;
UPDATE quiz_submission SET score = correct_count, max_score = total_count;

