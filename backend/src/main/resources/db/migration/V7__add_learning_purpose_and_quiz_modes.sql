-- 점수는 서버 코드가 합산한다. 기존 제출은 맞힌 수 = 점수, 문제 수 = 만점
ALTER TABLE quiz_submission ADD COLUMN score INTEGER DEFAULT 0 NOT NULL;
ALTER TABLE quiz_submission ADD COLUMN max_score INTEGER DEFAULT 0 NOT NULL;
