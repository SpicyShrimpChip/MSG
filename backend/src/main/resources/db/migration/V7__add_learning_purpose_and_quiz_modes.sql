-- 학습 목적·관심 직무와 3가지 학습 모드 퀴즈(시험 대비·자기개발·업무 활용), 객관식·주관식·서술형 문제.
-- 기존 행은 지우거나 바꾸지 않는다. 새 칸은 NULL을 허용하거나 기존 동작과 같은 기본값을 둔다
-- (V6 퀴즈는 모드 NULL·객관식, V6 제출은 맞힌 수 = 점수).
-- H2(PostgreSQL 모드)와 PostgreSQL에서 모두 돌도록 DB 전용 문법을 쓰지 않는다

-- ---------- 회원: 학습 목적·관심 직무 ----------
-- 주된 학습 목적. 기존 회원은 '아직 정하지 않음'. 퀴즈를 만들 때는 이와 다른 모드를 골라도 된다
ALTER TABLE users ADD COLUMN learning_purpose VARCHAR(20) DEFAULT 'UNDECIDED' NOT NULL;
-- 관심 직무 (업무 활용 모드에서 쓴다). 고르지 않았으면 NULL. 목록은 코드(JobField)에 있고 늘릴 수 있다
ALTER TABLE users ADD COLUMN job_field VARCHAR(40) NULL;
-- 관심 직무가 '기타'일 때 직접 쓴 분야 이름 (짧게)
ALTER TABLE users ADD COLUMN job_field_other VARCHAR(30) NULL;

-- ---------- 퀴즈: 모드·생성 조건 ----------
-- 학습 모드. V6에서 만든 퀴즈는 NULL(모드 없음)
ALTER TABLE quiz ADD COLUMN mode VARCHAR(20) NULL;
ALTER TABLE quiz ADD COLUMN difficulty VARCHAR(10) NULL;
-- 업무 활용 퀴즈를 만들 때 쓴 직무. 고르지 않았으면 NULL(일반 실무)
ALTER TABLE quiz ADD COLUMN job_field VARCHAR(40) NULL;
ALTER TABLE quiz ADD COLUMN job_field_other VARCHAR(30) NULL;
-- 사용자가 적은 시험 범위 (선택)
ALTER TABLE quiz ADD COLUMN exam_scope VARCHAR(200) NULL;
-- 문제를 만든 AI 제공사·모델. 사람이 넣은 퀴즈(V6)는 NULL
ALTER TABLE quiz ADD COLUMN generated_provider VARCHAR(10) NULL;
ALTER TABLE quiz ADD COLUMN generated_model VARCHAR(100) NULL;

-- AI가 제안한 다음 학습 개념 (자기개발 모드). 실제 풀이 결과와 섞지 않으려고 따로 둔다
CREATE TABLE quiz_suggestion (
    quiz_id    BIGINT       NOT NULL,
    sort_order INTEGER      NOT NULL,
    -- next: 다음 단계 / prerequisite: 보완할 선수 지식 / related: 연관 분야
    kind       VARCHAR(20)  NOT NULL,
    concept    VARCHAR(40)  NOT NULL,
    reason     VARCHAR(300) NULL,
    PRIMARY KEY (quiz_id, sort_order),
    CONSTRAINT fk_quiz_suggestion_quiz FOREIGN KEY (quiz_id) REFERENCES quiz (id) ON DELETE CASCADE
);

-- 퀴즈 만들기 요청 기록. 같은 요청(request_key)을 두 번 보내도 한 번만 만들고, 실패 이유와 호출량을 남긴다
CREATE TABLE quiz_generation (
    id               BIGINT       GENERATED BY DEFAULT AS IDENTITY,
    user_id          BIGINT       NOT NULL,
    course_id        BIGINT       NOT NULL,
    -- 프론트가 만든 요청 키 (같은 버튼을 두 번 눌러도 퀴즈가 하나만 생기게)
    request_key      VARCHAR(64)  NOT NULL,
    mode             VARCHAR(20)  NOT NULL,
    -- 고른 문제 유형 (쉼표로 이음, 예: MULTIPLE_CHOICE,ESSAY)
    question_types   VARCHAR(60)  NOT NULL,
    question_count   INTEGER      NOT NULL,
    difficulty       VARCHAR(10)  NOT NULL,
    -- RUNNING / SUCCEEDED / FAILED
    status           VARCHAR(20)  NOT NULL,
    -- 실패 이유 코드 (사용자 문구는 코드에서 만든다). 성공이면 NULL
    error_code       VARCHAR(30)  NULL,
    provider         VARCHAR(10)  NULL,
    model            VARCHAR(100) NULL,
    -- 만든 퀴즈. 퀴즈를 지우면 기록만 남는다
    quiz_id          BIGINT       NULL,
    input_tokens     INTEGER      NULL,
    output_tokens    INTEGER      NULL,
    attempts         INTEGER      DEFAULT 0 NOT NULL,
    created_at       TIMESTAMP(6) NOT NULL,
    finished_at      TIMESTAMP(6) NULL,
    PRIMARY KEY (id),
    CONSTRAINT uk_quiz_generation_request UNIQUE (user_id, request_key),
    CONSTRAINT fk_quiz_generation_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT fk_quiz_generation_course FOREIGN KEY (course_id) REFERENCES course (id) ON DELETE CASCADE,
    CONSTRAINT fk_quiz_generation_quiz FOREIGN KEY (quiz_id) REFERENCES quiz (id) ON DELETE SET NULL
);

CREATE INDEX idx_quiz_generation_user ON quiz_generation (user_id, created_at);

-- ---------- 문제: 유형·정답·채점 기준 ----------
-- 기존 문제는 모두 객관식
ALTER TABLE quiz_question ADD COLUMN question_type VARCHAR(20) DEFAULT 'MULTIPLE_CHOICE' NOT NULL;
-- 객관식만 정답 번호가 있다 (주관식·서술형은 NULL)
ALTER TABLE quiz_question ALTER COLUMN correct_choice_index DROP NOT NULL;
-- 업무 활용 문제의 상황·사용자 역할 (다른 모드는 NULL)
ALTER TABLE quiz_question ADD COLUMN scenario VARCHAR(2000) NULL;
ALTER TABLE quiz_question ADD COLUMN work_role VARCHAR(200) NULL;
-- 답변 작성 안내 (주관식·서술형)
ALTER TABLE quiz_question ADD COLUMN answer_guide VARCHAR(500) NULL;
-- 참고 모범 답안 (AI). 제출 뒤 결과에만 내보낸다
ALTER TABLE quiz_question ADD COLUMN model_answer VARCHAR(4000) NULL;

-- 주관식 허용 답 (여러 표현). 제출 뒤 결과에만 내보낸다
CREATE TABLE quiz_question_accepted_answer (
    question_id BIGINT       NOT NULL,
    sort_order  INTEGER      NOT NULL,
    content     VARCHAR(100) NOT NULL,
    PRIMARY KEY (question_id, sort_order),
    CONSTRAINT fk_quiz_accepted_answer_question FOREIGN KEY (question_id)
        REFERENCES quiz_question (id) ON DELETE CASCADE
);

-- 서술형 채점 기준과 배점. 배점 합이 그 문제의 만점이다
CREATE TABLE quiz_question_rubric (
    question_id BIGINT       NOT NULL,
    sort_order  INTEGER      NOT NULL,
    criterion   VARCHAR(200) NOT NULL,
    points      INTEGER      NOT NULL,
    PRIMARY KEY (question_id, sort_order),
    CONSTRAINT fk_quiz_rubric_question FOREIGN KEY (question_id)
        REFERENCES quiz_question (id) ON DELETE CASCADE
);

