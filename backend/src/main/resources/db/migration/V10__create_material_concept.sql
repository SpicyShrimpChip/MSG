-- 학습자료에서 뽑은 핵심 개념과 근거(자료 안의 위치·문장). 사전·사후평가가 이 개념 체계로 문제를 만든다.
-- 자료나 회원을 지우면 함께 지워진다. 자료 본문 전체는 저장하지 않고, 근거 문장(300자까지)만 남긴다.
-- H2(PostgreSQL 모드)와 PostgreSQL에서 모두 돈다

CREATE TABLE material_concept (
    id               BIGINT       GENERATED BY DEFAULT AS IDENTITY,
    material_id      BIGINT       NOT NULL,
    user_id          BIGINT       NOT NULL,
    sort_order       INTEGER      NOT NULL,
    -- 개념 이름을 소문자로 맞춘 값 (퀴즈 개념 키·과목 키워드와 같은 규칙)
    concept_key      VARCHAR(20)  NOT NULL,
    name             VARCHAR(20)  NOT NULL,
    -- AI가 쓴 짧은 설명
    description      VARCHAR(300) NULL,
    -- 근거 위치 (서버가 본문에서 찾은 쪽·슬라이드, 예: "p. 3", "슬라이드 2"). 위치 표시가 없는 글이면 NULL
    evidence_location VARCHAR(40) NULL,
    -- 근거 문장. 서버가 실제 본문에 있는지 확인한 것만 저장한다
    evidence_quote   VARCHAR(300) NOT NULL,
    -- 과목 키워드와 같은 개념인지 (자료에서 새로 찾은 개념과 구분)
    course_keyword   BOOLEAN      NOT NULL,
    provider         VARCHAR(10)  NOT NULL,
    model            VARCHAR(100) NULL,
    created_at       TIMESTAMP(6) NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT uk_material_concept UNIQUE (material_id, concept_key),
    CONSTRAINT fk_material_concept_material FOREIGN KEY (material_id) REFERENCES material (id) ON DELETE CASCADE,
    CONSTRAINT fk_material_concept_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE
);

CREATE INDEX idx_material_concept_material ON material_concept (material_id, sort_order);

