-- 근거 기반 학습 (feat/evidence-based-ai-learning). 열과 표를 더하기만 하고 기존 데이터는 바꾸지 않는다.
-- V4는 main의 V4__user_ai_call_daily.sql(#234)이 쓰므로 V5다. 이 파일은 V4 표와 관계가 없어 어느 순서로 적용돼도 된다.
-- 더한 열은 모두 NULL을 허용한다: 이 버전 전에 만든 퀴즈·분석은 값이 없고, 화면은 "기록 없음"으로 보여 준다.

-- ==================== 퀴즈: 인지 수준(개정 블룸)과 자료 출처 ====================

-- 이 퀴즈에서 평가하려고 고른 인지 수준 (쉼표로 이은 값, 예: "REMEMBER,UNDERSTAND,APPLY"). 난이도(difficulty)와 별개다
ALTER TABLE quiz ADD COLUMN bloom_targets VARCHAR(100) NULL;
-- 문제를 만든 지시문 버전 (예: quiz-gen-v6). 이 열을 더하기 전 퀴즈는 NULL
ALTER TABLE quiz ADD COLUMN prompt_version VARCHAR(40) NULL;
-- 자료 본문을 쓴 퀴즈: AI에 실제로 보낸 자료 부분의 위치 (서버가 고른 쪽·슬라이드·문단, 예: "p. 3, p. 4, p. 7")
ALTER TABLE quiz ADD COLUMN material_scope VARCHAR(300) NULL;
-- 자료 본문을 쓴 퀴즈: 요청한 개념 중 자료 본문에서 찾지 못한 개념 (쉼표로 이음). 모두 찾았으면 NULL
ALTER TABLE quiz ADD COLUMN material_missing_concepts VARCHAR(300) NULL;

-- 문제가 평가하는 인지 수준: REMEMBER / UNDERSTAND / APPLY / ANALYZE / EVALUATE / CREATE.
-- AI가 지정한 값이고 서버는 형식(요청한 수준 안인지, 창조는 서술형인지)만 확인한다. 실제 사고 수준을 코드로 판정한 값이 아니다
ALTER TABLE quiz_question ADD COLUMN bloom_level VARCHAR(20) NULL;
-- 출제 목표 ("~을 설명할 수 있다"처럼 이 문제로 확인하려는 것, AI)
ALTER TABLE quiz_question ADD COLUMN learning_objective VARCHAR(300) NULL;
-- 자료 근거: AI가 든 인용문 중 서버가 보낸 자료 부분에서 찾은 것, 그 위치(서버가 찾은 값), 검증 상태
ALTER TABLE quiz_question ADD COLUMN source_quote VARCHAR(300) NULL;
ALTER TABLE quiz_question ADD COLUMN source_location VARCHAR(40) NULL;
-- VERIFIED(원문과 일치) / PARTIAL(일부 일치) / FAILED(원문에서 찾지 못함) / INSUFFICIENT(인용 없음). 자료 없이 만든 문제는 NULL
ALTER TABLE quiz_question ADD COLUMN source_check VARCHAR(20) NULL;
-- 검증 메모 (예: AI가 적은 위치와 실제 위치가 달라 고침)
ALTER TABLE quiz_question ADD COLUMN source_note VARCHAR(200) NULL;
-- 정답 표현(객관식 정답 보기·주관식 허용 답)이 근거 부분에 나오는지 (참고 신호, 사실성 검증이 아니다). 서술형·자료 없음은 NULL
ALTER TABLE quiz_question ADD COLUMN answer_in_source BOOLEAN NULL;

-- ==================== 대화 분석: 학습 행동과 오개념 후보 ====================

-- 근거 메시지의 학습 행동 (AI 분류, 사용자 메시지만): CONFUSION_EXPRESSED / RE_EXPLANATION_REQUEST / DEEPENING_QUESTION /
-- INCORRECT_EXPLANATION / CORRECT_EXPLANATION / APPLICATION / NO_SIGNAL. concept-analysis-v1 결과와 AI 메시지는 NULL
ALTER TABLE analysis_judgment_evidence ADD COLUMN behavior VARCHAR(30) NULL;
-- 오개념 후보: 사용자의 잘못된 자기 설명에서 무엇이 틀렸다고 봤는지 (AI). 잘못된 설명 근거가 없으면 서버가 버린다
ALTER TABLE analysis_concept_judgment ADD COLUMN misconception VARCHAR(300) NULL;

-- ==================== 학습자료 요약본 ====================

-- 자료 하나·학습 목적 하나에 요약본 하나. 다시 만들면 같은 행을 바꾼다. 자료나 회원을 지우면 함께 지워진다.
-- 자료 본문 전체는 저장하지 않고, 요약 결과(AI 글 + 서버가 원문에서 확인한 인용문·위치)만 남긴다
CREATE TABLE material_summary (
    id                  BIGINT         GENERATED BY DEFAULT AS IDENTITY,
    user_id             BIGINT         NOT NULL,
    material_id         BIGINT         NOT NULL,
    -- 학습 목적: EXAM_PREP / SELF_DEVELOPMENT / WORK (퀴즈 학습 모드와 같은 값)
    purpose             VARCHAR(20)    NOT NULL,
    -- RUNNING(만드는 중) / SUCCEEDED / FAILED. 다시 만들다 실패하면 이전 결과가 있을 때 SUCCEEDED로 되돌린다
    status              VARCHAR(20)    NOT NULL,
    -- 만드는 중일 때의 마감 시각 (지나면 끝난 것으로 본다)
    deadline_at         TIMESTAMP(6)   NULL,
    -- 요약을 만든 원본 파일의 SHA-256 (자료 버전). 지금 파일과 다르면 화면에 "자료가 바뀌었어요"를 보여 준다
    content_hash        VARCHAR(64)    NULL,
    prompt_version      VARCHAR(40)    NULL,
    provider            VARCHAR(10)    NULL,
    model               VARCHAR(100)   NULL,
    -- 요약 결과 (서버가 검증해 다시 쓴 JSON). TEXT 대신 VARCHAR (V1 머리말 참고)
    summary_json        VARCHAR(30000) NULL,
    -- 전체 검증 상태: VERIFIED / PARTIAL / NEEDS_CHECK / INSUFFICIENT
    verification_status VARCHAR(20)    NULL,
    -- AI에 보낸 자료 범위 (서버가 고른 쪽·슬라이드·문단)와 원문이 길어 일부만 보냈는지
    source_scope        VARCHAR(300)   NULL,
    source_truncated    BOOLEAN        DEFAULT FALSE NOT NULL,
    created_at          TIMESTAMP(6)   NULL,
    updated_at          TIMESTAMP(6)   NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT uk_material_summary_purpose UNIQUE (material_id, purpose),
    CONSTRAINT fk_material_summary_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT fk_material_summary_material FOREIGN KEY (material_id) REFERENCES material (id) ON DELETE CASCADE
);

CREATE INDEX idx_material_summary_user ON material_summary (user_id);
