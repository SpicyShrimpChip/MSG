-- 개념별 학습 기록 (사용자가 자료의 핵심 개념을 공부하고 "학습 완료"를 누른 기록).
-- 개념은 (자료, 개념 키)로 가리킨다: material_concept 행은 "다시 뽑기" 때 새로 만들어져 id가 바뀌지만, 개념 키는 그대로라 기록이 이어진다.
-- 같은 이름의 개념도 자료가 다르면 다른 기록이다. 사용자·자료마다 개념 하나에 한 행(중복 완료 방지).
-- "학습 완료"는 공부했다는 기록일 뿐 이해했다는 뜻이 아니다. 이해 여부는 확인 퀴즈(아래 quiz.check_concept_key) 채점 결과로만 정한다.
-- 퀴즈 결과는 이 표에 복사하지 않고 퀴즈 기록에서 읽는다(다시 채점하면 바로 반영, 지난 결과는 퀴즈 행으로 남는다).
-- 회원·과목·자료를 지우면 함께 지워진다. H2(PostgreSQL 모드)와 PostgreSQL에서 모두 돈다

CREATE TABLE concept_study_progress (
    id                  BIGINT       GENERATED BY DEFAULT AS IDENTITY,
    user_id             BIGINT       NOT NULL,
    course_id           BIGINT       NOT NULL,
    material_id         BIGINT       NOT NULL,
    -- material_concept.concept_key와 같은 값 (개념 이름을 소문자로 맞춘 값)
    concept_key         VARCHAR(20)  NOT NULL,
    -- 표시용 개념 이름 (기록할 때의 이름)
    concept_name        VARCHAR(20)  NOT NULL,
    first_completed_at  TIMESTAMP(6) NOT NULL,
    last_studied_at     TIMESTAMP(6) NOT NULL,
    -- 학습 완료 횟수: 처음 1, "복습 필요"였다가 다시 공부하고 완료하면 1씩 늘어난다 (같은 상태에서 다시 눌러도 늘지 않는다)
    study_count         INTEGER      NOT NULL,
    created_at          TIMESTAMP(6) NOT NULL,
    updated_at          TIMESTAMP(6) NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT uk_concept_study_progress UNIQUE (user_id, material_id, concept_key),
    CONSTRAINT fk_concept_study_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT fk_concept_study_course FOREIGN KEY (course_id) REFERENCES course (id) ON DELETE CASCADE,
    CONSTRAINT fk_concept_study_material FOREIGN KEY (material_id) REFERENCES material (id) ON DELETE CASCADE
);

CREATE INDEX idx_concept_study_course ON concept_study_progress (user_id, course_id);

-- 개념 확인 퀴즈: 자료(quiz.material_id)의 개념 하나만 다루는 퀴즈. 일반 퀴즈·모의시험·사전·사후평가는 NULL
ALTER TABLE quiz ADD COLUMN check_concept_key VARCHAR(20) NULL;
ALTER TABLE quiz ADD COLUMN check_concept_name VARCHAR(20) NULL;

CREATE INDEX idx_quiz_check_concept ON quiz (user_id, material_id, check_concept_key);
