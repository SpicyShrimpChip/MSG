-- 학습자료(올린 파일의 정보)와, 지우지 못한 저장소 파일을 다시 지우기 위한 작업 목록.
-- 파일 내용은 저장소(global/storage, 지금은 로컬 디스크)에 두고 DB에는 정보와 저장 위치(storage_key)만 둔다.
-- H2(PostgreSQL 모드)와 PostgreSQL에서 모두 돌도록 DB 전용 문법을 쓰지 않는다

CREATE TABLE material (
    id                 BIGINT       GENERATED BY DEFAULT AS IDENTITY,
    user_id            BIGINT       NOT NULL,
    -- 과목에 연결하지 않은 자료는 NULL
    course_id          BIGINT       NULL,
    title              VARCHAR(60)  NOT NULL,
    -- 화면에 보여 줄 원래 파일 이름 (경로 부분을 떼고 정리한 값). 저장 위치에는 쓰지 않는다
    original_file_name VARCHAR(255) NOT NULL,
    -- 서버가 내용을 확인한 형식: PDF, PPTX, TXT, MD
    file_format        VARCHAR(10)  NOT NULL,
    -- 형식에서 정한 MIME (브라우저가 보낸 값을 믿지 않는다)
    content_type       VARCHAR(100) NOT NULL,
    file_size          BIGINT       NOT NULL,
    -- 저장소 안의 위치. 서버가 만든 값(materials/{user_id}/{UUID}.{확장자})이다.
    -- 원본 보관 정책이 정해져 원본만 지우는 경우를 위해 NULL을 허용한다
    storage_key        VARCHAR(200) NULL,
    -- UPLOADED(저장 완료, AI 분석 전) / PROCESSING / READY / FAILED
    status             VARCHAR(20)  NOT NULL,
    created_at         TIMESTAMP(6) NOT NULL,
    updated_at         TIMESTAMP(6) NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT uk_material_storage_key UNIQUE (storage_key),
    -- 회원 탈퇴 때 행은 함께 지워진다. 저장소 파일은 탈퇴 처리 코드가 따로 지워야 한다 (docs/backend-design.md)
    CONSTRAINT fk_material_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
    -- 과목을 지우면 그 과목의 자료도 지운다. 앱은 파일 정리 작업을 남기려고 자료를 먼저 지우고, 이 제약은 마지막 안전장치다
    CONSTRAINT fk_material_course FOREIGN KEY (course_id) REFERENCES course (id) ON DELETE CASCADE
);

CREATE INDEX idx_material_user_created ON material (user_id, created_at);
CREATE INDEX idx_material_course ON material (course_id);

-- 지워야 할 저장소 파일. 자료 행을 지우는 트랜잭션에서 함께 만들고, 커밋 뒤 파일을 지우면 행도 지운다.
-- 파일을 지우지 못하면 행이 남아 주기 작업이 다시 지운다 (FileCleanupService)
CREATE TABLE file_deletion_task (
    id                BIGINT       GENERATED BY DEFAULT AS IDENTITY,
    storage_key       VARCHAR(200) NOT NULL,
    attempt_count     INTEGER      NOT NULL,
    created_at        TIMESTAMP(6) NOT NULL,
    last_attempted_at TIMESTAMP(6) NULL,
    PRIMARY KEY (id)
);
