-- 내 과목 (학습자료 > 내 과목). 과목은 로그인한 사용자별로 나뉜다.
-- H2(PostgreSQL 모드)와 PostgreSQL에서 모두 돌도록 DB 전용 문법을 쓰지 않는다 (V1과 같은 규칙)

CREATE TABLE course (
    id         BIGINT       GENERATED BY DEFAULT AS IDENTITY,
    user_id    BIGINT       NOT NULL,
    name       VARCHAR(40)  NOT NULL,
    -- 중복 검사용: 이름을 소문자로 바꾼 값. 같은 사용자·같은 학기에 대소문자만 다른 이름도 막는다
    -- (H2와 PostgreSQL이 함께 쓰는 문법으로는 LOWER(name) 인덱스를 만들 수 없어 컬럼으로 둔다)
    name_key   VARCHAR(80)  NOT NULL,
    -- '2026-1', '2026-summer', '2026-2', '2026-winter'
    semester   VARCHAR(20)  NOT NULL,
    created_at TIMESTAMP(6) NOT NULL,
    updated_at TIMESTAMP(6) NOT NULL,
    PRIMARY KEY (id),
    -- user_id로 시작하므로 사용자별 과목 조회 인덱스도 겸한다
    CONSTRAINT uk_course_user_semester_name UNIQUE (user_id, semester, name_key),
    CONSTRAINT fk_course_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE
);

-- 과목 키워드. AI 대화 가져오기에서 공부한 대화를 고를 때 쓴다. 입력한 순서를 sort_order로 지킨다
CREATE TABLE course_keyword (
    course_id  BIGINT      NOT NULL,
    sort_order INTEGER     NOT NULL,
    keyword    VARCHAR(20) NOT NULL,
    PRIMARY KEY (course_id, sort_order),
    CONSTRAINT fk_course_keyword_course FOREIGN KEY (course_id) REFERENCES course (id) ON DELETE CASCADE
);
