-- 학습 대화 개념 분석 (1차): 여러 AI 모델(GPT·Claude·Gemini)이 같은 대화를 독립적으로 분석한 결과와 모델 사이 비교,
-- 그리고 학습 모드에서 사용자가 남긴 피드백. AI 결과는 받은 그대로 보관하고, 사용자 피드백은 따로 둔다.
-- 숙련도 점수는 여기서 만들지 않는다 (점수는 코드 규칙으로 계산하며 산식은 미결, docs/backend-design.md).
-- H2(PostgreSQL 모드)와 PostgreSQL에서 모두 돌도록 DB 전용 문법을 쓰지 않는다

-- 분석 한 번 = 과목 하나의 분석 대상 대화를 모든 모델에 한 번씩 보낸 것
CREATE TABLE analysis_run (
    id                      BIGINT       GENERATED BY DEFAULT AS IDENTITY,
    user_id                 BIGINT       NOT NULL,
    course_id               BIGINT       NOT NULL,
    -- RUNNING / COMPLETED(모든 호출 모델 성공) / PARTIAL(일부 성공) / FAILED(성공한 모델 없음)
    status                  VARCHAR(20)  NOT NULL,
    -- 모델에 준 지시문 버전. 지시문을 바꾸면 결과를 같은 기준으로 비교하지 않는다
    prompt_version          VARCHAR(40)  NOT NULL,
    conversation_count      INTEGER      NOT NULL,
    message_count           INTEGER      NOT NULL,
    -- 길어서 뒤를 잘라 보낸 메시지 수
    truncated_message_count INTEGER      NOT NULL,
    input_chars             INTEGER      NOT NULL,
    created_at              TIMESTAMP(6) NOT NULL,
    completed_at            TIMESTAMP(6) NULL,
    PRIMARY KEY (id),
    CONSTRAINT fk_analysis_run_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT fk_analysis_run_course FOREIGN KEY (course_id) REFERENCES course (id) ON DELETE CASCADE
);

CREATE INDEX idx_analysis_run_user_created ON analysis_run (user_id, created_at);
CREATE INDEX idx_analysis_run_course ON analysis_run (course_id);

-- 분석에 쓴 대화. 대화를 지우면 그 대화를 쓴 분석을 앱이 함께 지운다(AnalysisCleanup). 이 외래 키는 마지막 안전장치다
CREATE TABLE analysis_run_conversation (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY,
    run_id          BIGINT NOT NULL,
    conversation_id BIGINT NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT uk_analysis_run_conversation UNIQUE (run_id, conversation_id),
    CONSTRAINT fk_analysis_run_conversation_run FOREIGN KEY (run_id) REFERENCES analysis_run (id) ON DELETE CASCADE,
    CONSTRAINT fk_analysis_run_conversation_conversation FOREIGN KEY (conversation_id)
        REFERENCES conversation (id) ON DELETE CASCADE
);

CREATE INDEX idx_analysis_run_conversation_conversation ON analysis_run_conversation (conversation_id);

-- 모델 하나의 결과. 호출하지 않은 모델(키·모델 미설정)도 NOT_CONFIGURED로 남겨 몇 개 모델로 비교했는지 보여 준다
CREATE TABLE analysis_model_result (
    id                     BIGINT         GENERATED BY DEFAULT AS IDENTITY,
    run_id                 BIGINT         NOT NULL,
    -- GPT / CLAUDE / GEMINI
    provider               VARCHAR(20)    NOT NULL,
    model                  VARCHAR(100)   NULL,
    -- SUCCEEDED / FAILED / INVALID_OUTPUT / NOT_CONFIGURED
    status                 VARCHAR(20)    NOT NULL,
    error_code             VARCHAR(40)    NULL,
    -- 모델이 돌려준 글 그대로 (검증 전 원본, 최대 60,000자)
    raw_output             VARCHAR(60000) NULL,
    input_tokens           INTEGER        NULL,
    output_tokens          INTEGER        NULL,
    attempt_count          INTEGER        NOT NULL,
    latency_ms             BIGINT         NULL,
    -- 검증에서 버린 근거 수 (보낸 적 없는 메시지 id, 말한 사람이 맞지 않는 근거 등)
    dropped_evidence_count INTEGER        NOT NULL,
    created_at             TIMESTAMP(6)   NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT uk_analysis_model_result UNIQUE (run_id, provider),
    CONSTRAINT fk_analysis_model_result_run FOREIGN KEY (run_id) REFERENCES analysis_run (id) ON DELETE CASCADE
);

-- 모델 하나가 개념 하나에 내린 판단
CREATE TABLE analysis_concept_judgment (
    id                   BIGINT        GENERATED BY DEFAULT AS IDENTITY,
    model_result_id      BIGINT        NOT NULL,
    -- 과목 키워드를 소문자로 맞춘 값 (course_keyword와 같은 규칙). 모델 사이 비교에 쓴다
    concept_key          VARCHAR(20)   NOT NULL,
    concept_name         VARCHAR(20)   NOT NULL,
    -- 모델이 보고한 상태: UNDERSTOOD / PARTIAL / NOT_UNDERSTOOD / INSUFFICIENT_EVIDENCE
    reported_status      VARCHAR(30)   NOT NULL,
    -- 검증 뒤 비교에 쓰는 상태. 사용자가 쓴 메시지 근거가 하나도 없으면 INSUFFICIENT_EVIDENCE로 본다
    status               VARCHAR(30)   NOT NULL,
    adjusted_reason      VARCHAR(200)  NULL,
    reason               VARCHAR(1000) NULL,
    needs_check          VARCHAR(500)  NULL,
    recommended_activity VARCHAR(500)  NULL,
    PRIMARY KEY (id),
    CONSTRAINT uk_analysis_concept_judgment UNIQUE (model_result_id, concept_key),
    CONSTRAINT fk_analysis_concept_judgment_result FOREIGN KEY (model_result_id)
        REFERENCES analysis_model_result (id) ON DELETE CASCADE
);

-- 판단 근거가 된 메시지. 검증을 통과한 근거만 저장한다
CREATE TABLE analysis_judgment_evidence (
    id          BIGINT       GENERATED BY DEFAULT AS IDENTITY,
    judgment_id BIGINT       NOT NULL,
    message_id  BIGINT       NOT NULL,
    -- USER_EXPLANATION / USER_SOLUTION / USER_QUESTION (사용자가 쓴 글) / AI_EXPLANATION (AI가 준 설명)
    kind        VARCHAR(30)  NOT NULL,
    note        VARCHAR(300) NULL,
    PRIMARY KEY (id),
    CONSTRAINT fk_analysis_judgment_evidence_judgment FOREIGN KEY (judgment_id)
        REFERENCES analysis_concept_judgment (id) ON DELETE CASCADE,
    CONSTRAINT fk_analysis_judgment_evidence_message FOREIGN KEY (message_id)
        REFERENCES conversation_message (id) ON DELETE CASCADE
);

CREATE INDEX idx_analysis_judgment_evidence_judgment ON analysis_judgment_evidence (judgment_id);
CREATE INDEX idx_analysis_judgment_evidence_message ON analysis_judgment_evidence (message_id);

-- 개념별 모델 비교 결과 (코드가 계산). 정확도나 숙련도 점수가 아니다
CREATE TABLE analysis_concept_consensus (
    id           BIGINT      GENERATED BY DEFAULT AS IDENTITY,
    run_id       BIGINT      NOT NULL,
    concept_key  VARCHAR(20) NOT NULL,
    concept_name VARCHAR(20) NOT NULL,
    -- UNANIMOUS / MAJORITY / DISAGREEMENT / SINGLE_MODEL / NO_RESULT
    outcome      VARCHAR(20) NOT NULL,
    -- 일치한 상태. 의견 불일치·결과 없음이면 NULL
    status       VARCHAR(30) NULL,
    -- 이 개념을 판단한 모델 수, 그중 같은 판단을 한 모델 수, 이번에 호출한 모델 수
    judged_count INTEGER     NOT NULL,
    agree_count  INTEGER     NOT NULL,
    called_count INTEGER     NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT uk_analysis_concept_consensus UNIQUE (run_id, concept_key),
    CONSTRAINT fk_analysis_concept_consensus_run FOREIGN KEY (run_id) REFERENCES analysis_run (id) ON DELETE CASCADE
);

-- 학습 모드에서 사용자가 개념마다 남긴 의견 (이미 알아요 / 더 공부할래요). AI 결과와 숙련도를 바꾸지 않는다.
-- 과목·개념마다 하나이고, 수정하면 덮어쓰고 취소하면 지운다
CREATE TABLE concept_feedback (
    id              BIGINT       GENERATED BY DEFAULT AS IDENTITY,
    user_id         BIGINT       NOT NULL,
    course_id       BIGINT       NOT NULL,
    concept_key     VARCHAR(20)  NOT NULL,
    concept_name    VARCHAR(20)  NOT NULL,
    -- ALREADY_KNOW / WANT_TO_STUDY
    feedback        VARCHAR(20)  NOT NULL,
    comment         VARCHAR(200) NULL,
    -- 피드백을 남길 때 보고 있던 분석 (그 분석이 지워지면 NULL)
    analysis_run_id BIGINT       NULL,
    created_at      TIMESTAMP(6) NOT NULL,
    updated_at      TIMESTAMP(6) NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT uk_concept_feedback UNIQUE (user_id, course_id, concept_key),
    CONSTRAINT fk_concept_feedback_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT fk_concept_feedback_course FOREIGN KEY (course_id) REFERENCES course (id) ON DELETE CASCADE,
    CONSTRAINT fk_concept_feedback_run FOREIGN KEY (analysis_run_id) REFERENCES analysis_run (id) ON DELETE SET NULL
);
